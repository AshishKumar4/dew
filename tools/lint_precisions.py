"""SLOP034's reading of a file, for tools/lint_slop.py: a contraction whose precision is named outright,
JAX's `Precision.HIGHEST` read through any name its enum is imported as or 'highest' as a call's
`precision=`, in `src/<package>` outside its precision policy (`POLICY`). A layer's product takes the run's
(`dew.nn.precision.computed_einsum`, `computed_dot`) and a genuinely exact boundary names itself
(`EXACT_FLOAT32`, `exact_float32`), so a bf16 run's Tensor Cores and `ACCURATE`'s float32 reach every model
contraction (the owner, 2026-11-25; row 12921). A generated module (`GENERATED`) prints the programs it was
traced from, their precisions among them, and is its generator's to read.
"""

from __future__ import annotations

import ast
from collections.abc import Iterator, Sequence

import lint_scopes as scopes

POLICY = ("nn/precision.py", "nn/programs.py")
"""The modules that name a contraction's precision outright: the policy, and the arithmetic catalog beneath
it, which names the algorithms each precision lowers to."""
GENERATED = "Generated by "
"""How a generated module's docstring opens (`dew.algebra.generate`'s, a traced program printed)."""
NAMED_OUTRIGHT = ("a precision named outright; take the run's (dew.nn.precision.computed_einsum) or name an "
                  "exact boundary (dew.nn.precision.EXACT_FLOAT32)")


def precisions(relative: str, package: str, tree: ast.Module,
               parent: Sequence[str]) -> Iterator[tuple[int, int, str]]:
    """SLOP034's findings in the module at `relative` of `package`'s checkout, parsed as `tree`, each name
    read in its own scope (`lint_scopes.scoped`, `parent` the package for relative imports): each one's
    line, column and message."""
    prefix = f"src/{package}/"
    docstring = ast.get_docstring(tree) or ""
    if (not relative.startswith(prefix) or relative.removeprefix(prefix) in POLICY
            or docstring.startswith(GENERATED)):
        return
    for node, table in scopes.scoped(tree.body, {}, parent):
        if isinstance(node, ast.Attribute) and node.attr == "HIGHEST":
            named = scopes.resolved(node.value, table)
            if named.startswith("jax.") and named.endswith(".Precision"):
                yield node.lineno, node.col_offset + 1, NAMED_OUTRIGHT
        elif isinstance(node, ast.Call):
            for keyword in node.keywords:
                value = keyword.value
                if (keyword.arg == "precision" and isinstance(value, ast.Constant)
                        and isinstance(value.value, str) and value.value.lower() == "highest"):
                    yield value.lineno, value.col_offset + 1, NAMED_OUTRIGHT
