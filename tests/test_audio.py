FIXTURES = Path(__file__).parent / "fixtures" / "audio"

on_gpu = pytest.mark.gpu(reason="needs a cuda device")


def _audio(kind):
    path = FIXTURES / kind
    record = json.loads((path / "config.json").read_text())
    config = audio_config(record)
    variables, _ = audio_weights(load_file(str(path / "encoder.safetensors")), config)
    model = config.build().clone(precision=jax.lax.Precision.HIGHEST)
    tensors = load_file(str(path / "projector.safetensors"))
    if kind == "gemma3n":
        projector = Gemma3nProjector(config.hidden_size, 32, vocab_size=record["vocab_size"],
                                           vocab_offset=record["vocab_offset"], norm_eps=config.rms_norm_eps,
                                           precision=jax.lax.Precision.HIGHEST)
        method = projector.soft_embeddings
        projector_variables = {"params": translate_gemma3n_projector_weights(tensors)[0]}
    else:
        projector = Gemma4Projector(text_width=32, norm_eps=config.rms_norm_eps,
                                          precision=jax.lax.Precision.HIGHEST)
        method = projector.__call__
        projector_variables = {"params": translate_gemma4_projector_weights(tensors)[0]}
    return path, config, variables, model, projector, method, projector_variables


@pytest.fixture(params=("gemma3n", "gemma4"), scope="module")
def audio(request):
    return _audio(request.param)

def test_waveform_preprocessing_encoder_and_projection_match_reference(audio):
    path, config, variables, model, projector, method, projector_variables = audio
    data = np.load(path / "reference.npz")
    preprocessor = json.loads((path / "preprocessor_config.json").read_text())
    kind = "gemma3n_audio" if isinstance(config, Gemma3nAudio) else "gemma4_audio"
    waveforms = [np.load(path / f"waveform_{index}.npy") for index in range(2)]
    features = gemma_features(kind, preprocessor, waveforms)
    np.testing.assert_array_equal(features["input_features_mask"], data["input_features_mask"])
    np.testing.assert_allclose(features["input_features"], data["input_features"], rtol=0, atol=1e-6)
    encoded = jax.jit(model.apply)(variables, **features)
    np.testing.assert_array_equal(encoded.mask, data["valid"])
    np.testing.assert_allclose(encoded.features, data["encoded"], rtol=0, atol=1e-4)
    projected = projector.apply(projector_variables, encoded.features, method=method)
    np.testing.assert_allclose(projected, data["projected"], rtol=0, atol=1e-4)
    assert encoded.mask.dtype == jnp.bool_
    assert encoded.features.dtype == jnp.float32

    if kind == "gemma4_audio":
        bounds = jax.tree_util.tree_map_with_path(
            lambda path, value: jnp.full_like(value, -jnp.inf if path[-1].key.endswith("min") else jnp.inf),
            variables["constants"])
        changed = jax.jit(model.apply)({**variables, "constants": bounds}, **features)
        assert np.max(np.abs(np.asarray(changed.features) - data["encoded"])) > 1e-3
        # The loaded FP32 bounds clamp in the operand's dtype, as torch.clamp
        # does, so a bf16 tower stays bf16 through every clipped map, and its
        # output is as near the float32 tower's as the reference's bf16 tower.
        lowered, state = jax.jit(lambda variables: model.clone(dtype=jnp.bfloat16).apply(
            variables, **features, capture_intermediates=lambda module, _: isinstance(module, AudioLinear)))(
            variables)
        assert {leaf.dtype for leaf in jax.tree.leaves(state["intermediates"])} == {jnp.dtype(jnp.bfloat16)}
        real = np.asarray(data["valid"], bool)
        truth = np.asarray(data["encoded"], np.float64)[real]
        assert_as_exact_as_the_reference(np.asarray(lowered.features, np.float32)[real],
                                         data["encoded_bf16"][real], truth, "bf16 encoded")


def test_a_gemma4_tower_runs_any_activation_the_shared_table_computes_as_the_reference_does():
    """`hidden_act` may name any activation the shared table computes,
    quick_gelu here, and a tower so configured loads. Its feed-forwards and
    light convolution, the blocks the activation runs in, each compute the
    reference's block with the tower's own weights: in fp32, as exact as the
    reference's fp32 block from its float64 run. The whole reference tower pins
    its attention to float32, so the blocks run alone."""
    import torch
    from transformers.models.gemma4.modeling_gemma4 import Gemma4AudioModel

    from dew.nn.audio import AudioFeedForward, AudioLightConv, _clippable
    from tools import audio_reference

    config = audio_reference.audio_config("gemma4")
    config.hidden_act = "quick_gelu"
    torch.manual_seed(314)
    reference = Gemma4AudioModel(config).eval()
    audio_reference.perturb(reference)
    ours = audio_config(config.to_dict())
    tensors = {name: tensor.numpy().copy() for name, tensor in reference.state_dict().items()}
    tree, _ = audio_weights(tensors, ours)
    linear = _clippable(ours, None, None)
    feed_forward = AudioFeedForward(ours.hidden_size, ours.residual_weight, ours.gradient_clipping, linear,
                                    ours.hidden_act)
    light_conv = AudioLightConv(ours.hidden_size, ours.conv_kernel_size, ours.rms_norm_eps,
                                ours.gradient_clipping, linear, ours.hidden_act)
    x = np.random.default_rng(5).normal(size=(2, 12, ours.hidden_size)).astype(np.float32)
    layer = reference.layers[0]
    blocks = {"feed_forward1": feed_forward, "lconv1d": light_conv, "feed_forward2": feed_forward}
    for name, block in blocks.items():
        theirs = getattr(layer, name)
        with torch.no_grad():
            wide, narrow = (theirs.to(dtype)(torch.from_numpy(x).to(dtype)).numpy()
                            for dtype in (torch.float64, torch.float32))
        variables = {collection: held["layers_0"][name] for collection, held in tree.items()
                     if name in held.get("layers_0", {})}
        assert_as_exact_as_the_reference(np.asarray(block.apply(variables, x)), narrow, wide, name)


@on_gpu
def test_encoder_compiles_on_gpu_with_the_mask_built_in_the_same_jit(audio):
    """Frame subsampling must leave no strided slice on a dot's operand chain.

    XLA's Triton GEMM fusion propagates a dot's tiling into its operands and
    mishandles a strided slice, aborting the process with
    `triton_tiling_propagation.cc: Check failed: src_fragment_it !=
    src_fragments_order.end()` as soon as anything fusible produces the
    sliced tensor. Deriving the mask from clip lengths inside the same jit
    puts such a producer above every frame subsample, which the encoder's
    former `mask[:, ::stride]` did not survive. Run with JAX_PLATFORMS=cuda.
    """
    path, _, variables, model, _, _, _ = audio
    data = np.load(path / "reference.npz")

    @jax.jit
    def encode(variables, features, lengths):
        return model.apply(variables, features,
                           jnp.arange(features.shape[1])[None, :] < lengths[:, None])

    encoded = encode(variables, jnp.asarray(data["input_features"]),
                     jnp.asarray(data["input_features_mask"].sum(1, dtype=np.int32)))
    np.testing.assert_array_equal(encoded.mask, data["valid"])
    np.testing.assert_allclose(encoded.features, data["encoded"], rtol=0, atol=1e-4)


def test_audio_input_gradients_and_sgd_step_match_reference(audio):
    path, _, variables, model, projector, method, projector_variables = audio
    data = np.load(path / "reference.npz")
    state = {"encoder": variables["params"], "projector": projector_variables["params"]}

    def forward(params, inputs):
        encoded = model.apply({**variables, "params": params["encoder"]}, inputs,
                               data["input_features_mask"])
        return projector.apply({"params": params["projector"]}, encoded.features, method=method)

    def loss(variables, inputs):
        return jnp.mean(forward(variables, inputs) * data["coefficient"])

    value, (grads, input_grad) = jax.jit(jax.value_and_grad(loss, argnums=(0, 1)))(
        state, data["input_features"]
    )
    np.testing.assert_allclose(value, data["loss"], rtol=0, atol=1e-6)
    np.testing.assert_allclose(input_grad, data["input_gradient"], rtol=1e-4, atol=1e-7)
    optimizer = optax.sgd(json.loads((path / "meta.json").read_text())["learning_rate"])
    update, _ = optimizer.update(grads, optimizer.init(state), state)
    output = jax.jit(forward)(optax.apply_updates(state, update), data["input_features"])
    np.testing.assert_allclose(output, np.load(path / "stepped.npy"), rtol=0, atol=1e-4)


def test_audio_mask_and_feature_shape_are_part_of_the_contract(audio):
    _, config, variables, model, _, _, _ = audio
    features = (
        config.input_feat_size if isinstance(config, Gemma3nAudio) else config.subsampling_conv_channels[0]
    )
    with pytest.raises(ValueError):
        model.apply(variables, jnp.ones((1, 16, features)), jnp.ones((1, 16), jnp.int32))
    with pytest.raises(ValueError):
        model.apply(variables, jnp.ones((1, 16, features + 1)), jnp.ones((1, 16), jnp.bool_))
    with pytest.raises(ValueError):
        model.apply(variables, jnp.ones((1, 16, features)), jnp.ones((1, 15), jnp.bool_))


def test_audio_weight_loading_refuses_unknown_or_missing_computation(audio):
    path, config, _, _, _, _, _ = audio
    tensors = load_file(str(path / "encoder.safetensors"))
    first = next(iter(tensors))
    incomplete = dict(tensors)
    del incomplete[first]
    with pytest.raises(ValueError):
        audio_weights(incomplete, config)
    with pytest.raises(ValueError):
        audio_weights({**tensors, "imaginary_projection.weight": np.ones((4, 4), np.float32)}, config)
    projection = next(name for name, tensor in tensors.items() if tensor.ndim >= 2)
    with pytest.raises(ValueError):
        audio_weights({**tensors, projection: tensors[projection][:-1]}, config)
    record = json.loads((path / "config.json").read_text())
    with pytest.raises(ValueError):
        audio_config({**record, "extra_computational_field": True})
    rebuilt = audio_config({**dataclasses.asdict(config), "model_type": record["model_type"]})
    assert rebuilt == config
    assert towers.from_record({"class": record["model_type"], "fields": dataclasses.asdict(config)}) == config


def test_audio_weight_paths_round_trip_every_checkpoint_tensor(audio):
    """The canonical mapper resolves each source tensor to its loaded leaf."""
    path, config, variables, _, _, _, _ = audio
    tensors = load_file(str(path / "encoder.safetensors"))
    for name, tensor in tensors.items():
        leaf = variables
        for part in audio_weight_path(name, config):
            leaf = leaf[part]
        restored = np.asarray(leaf)
        if tensor.ndim > 1:
            restored = restored.transpose(restored.ndim - 1, restored.ndim - 2, *range(restored.ndim - 2))
        np.testing.assert_array_equal(restored, tensor)


@pytest.mark.parametrize("config", [
    Gemma3nAudio(),
    Gemma3nAudio(conf_reduction_factor=2, input_feat_size=16, hidden_size=32, conf_num_attention_heads=2,
                 conf_num_hidden_layers=1, sscp_conv_channel_size=(8, 4)),
], ids=["released", "reduction_2"])
def test_a_gemma3n_tower_encodes_its_stated_frames_per_token_into_one_token(config):
    """A Gemma 3n tower encodes `frames_per_token` input frames a token, as its geometry states
    (`encoded_frame_stride`, the stride the processor counts by), which
    a token-only init sizes its fixed audio slots by: the released config (strides 2 x 2, reduction 4)
    and a tower reducing by 2 each encode three tokens' frames into three tokens."""
    per_token = config.geometry().frames_per_token
    frames = 3 * per_token
    encoder = config.build()
    features = jax.ShapeDtypeStruct((1, frames, config.input_feat_size), jnp.float32)
    mask = jax.ShapeDtypeStruct((1, frames), jnp.bool_)
    variables = jax.eval_shape(encoder.init, jax.random.key(0), features, mask)
    encoded = jax.eval_shape(encoder.apply, variables, features, mask)
    assert encoded.features.shape[1] == 3
