@contextlib.contextmanager
def _printed(**switches: str):
    """Mosaic GPU's `switches` on in the block (MOSAIC_GPU_DUMP_RESOURCES, MOSAIC_GPU_DUMP_PTX), which with no
    MOSAIC_GPU_DUMP_TO print what they dump: a list the block's printed text joins as it ends, Python's
    prints and the compiler's own output (fd 1) both. MOSAIC_GPU_DUMP_TO turns every dump on, its layout
    inference's constraint system among them, each variable printing its operation: 47.6 of a Kimi Linear
    A100 forward cell's 138 seconds (cProfile, armada, 9e65ee222). The gate compiles one case at a time in
    its process, which sets nothing else, as Mosaic reads these settings in every compile."""
    printed: list[str] = []
    with _PRINTING, tempfile.TemporaryFile() as native:
        before = {name: os.environ.get(name) for name in switches}
        os.environ.update(switches)
        python, saved = io.StringIO(), os.dup(1)
        os.dup2(native.fileno(), 1)
        try:
            with contextlib.redirect_stdout(python):
                yield printed
        finally:
            os.dup2(saved, 1)
            os.close(saved)
            for name, value in before.items():
                if value is None:
                    os.environ.pop(name, None)
                else:
                    os.environ[name] = value
            native.seek(0)
            printed += [python.getvalue(), native.read().decode(errors="replace")]


_BINARY_CAPABILITY: list[tuple[int, int]] = []
"""The compute capability this process's Mosaic GPU binary pass is registered with: the first kernel's it
compiled. jaxlib registers the pass once a process and assembles every later kernel for that capability
(custom_call.cc's GetPassPipeline; an sm_90a kernel after an sm80 one fails in ptxas, 'SM version
specified by .target is higher than default SM version assumed', and an sm80 kernel after an sm90 one is
assembled for sm90). Production compiles for one GPU a process; the gates compile for several."""


class Gated(str):
    """A generation a compile gate's cell compiles for (`gate_generations`): the typed fact a process of its
    own gathers the session's cells of one capability by (`compiled_apart`)."""


def gate_generations(dtype=jnp.bfloat16, *, stated: bool = False, scoped: bool = False, tpu: bool = False,
                     needs: Callable[[Any, Any], bool] | None = None) -> tuple[Gated, ...]:
    """The generations a compile gate's cells take for a template's launches of `dtype` (its launch's
    `stated`, `scoped` and `tpu`, as it asks `bundles.of`): one for each CUDA architecture Dew names a device
    of whose bundles serve the launch (`bundles.of` not None), the earliest named, so its launches are
    compiled on every family they run on (each architecture's multiprocessor and issuers,
    `generation.architecture`), never on a typed list (a recurrence gate of sm80 and sm90 alone left seven
    sm100 launches unseen). `needs(family, architecture)` is the
    typed fact a cell that is one family's by nature needs of it (an issuer, an instruction); every family's
    where None."""
    from dew.nn.kernels import generation
    from dew.nn.kernels.templates import bundles

    found: list[tuple[Any, str]] = []
    for name in sorted((name for name in generation.TARGETS if capability(name) is not None), key=capability):
        architecture = generation.architecture(name)
        family = bundles.of(name, dtype, stated=stated, scoped=scoped, tpu=tpu)
        if family is None or any(architecture == seen for seen, _ in found):
            continue
        if needs is None or needs(family, architecture):
            found.append((architecture, name))
    return tuple(Gated(name) for _, name in found)


def compile_mosaic_kernels(cases, generation: str) -> list[dict]:
    """Each Mosaic GPU case (`name`, `call()` giving the kernel and abstract operands) compiled as
    `compile_kernels` compiles Triton's, for a compile-only device of the CUDA `generation`, with Mosaic's
    own reports printed (`_printed`): its name, the generation's shared-memory and tensor-memory limits
    (`GpuTarget.tmem_columns`, 0 where it has none), and each of its kernels' report (`mosaic_kernels`),
    or the error. In a process that compiled Mosaic kernels for another capability
    (`_BINARY_CAPABILITY`) these are the records its process of its own gives (`compiled_apart`)."""
    wanted = capability(generation)
    test = os.environ.get("PYTEST_CURRENT_TEST", "").rsplit(" ", 1)[0]
    call = _CALLS[test]
    _CALLS[test] += 1
    if _BINARY_CAPABILITY and _BINARY_CAPABILITY[0] != wanted and apart_records.RECORDS not in os.environ:
        return compiled_apart(wanted, test, call)
    _BINARY_CAPABILITY[:] = _BINARY_CAPABILITY or [wanted]
    found = _compiled_here(cases, generation)
    if apart_records.RECORDS in os.environ:
        apart_records.written(Path(os.environ[apart_records.RECORDS]), test, call, found)
    return found


_CALLS: Counter[str] = Counter()
"""Each test's `compile_mosaic_kernels` calls so far, by node id: a process of its own keeps a test's records
by their order."""

_APART: dict[tuple[int, int] | str, Path] = {}
"""The directory each process of its own wrote, by the capability whose cells it ran, or by the one test it
ran where that test states no capability of the gate's (`compiled_apart`)."""


def compiled_apart(wanted: tuple[int, int], test: str, call: int) -> list[dict]:
    """The records of `test`'s `call`-th Mosaic GPU compile, for a capability other than the one this process
    compiles for, from a pytest process of its own: one a capability, the first test to ask it starting it
    with every test of the session whose cells state it (`_stated`), so a test of another capability costs
    no process of its own; a test it did not run (one that states no capability of the gate's) its own.
    Read only where the test passed there, as its records are written before its own checks and teardown
    (row 1877)."""
    if wanted not in _APART:
        _APART[wanted] = _ran_apart([test, *(item.nodeid for item in apart_records.SESSION
                                             if item.nodeid != test and _stated(item) == wanted)])
    directory = _APART[wanted]
    if not apart_records.ran(directory, test):
        if test not in _APART:
            _APART[test] = _ran_apart([test])
        directory = _APART[test]
    return apart_records.read(directory, test, call)


def _stated(item) -> tuple[int, int] | None:
    """The capability a session's test compiles for, where its cell states one generation of the gate's
    (`Gated`); None for any other test."""
    stated = {capability(value) for value in getattr(getattr(item, "callspec", None), "params", {}).values()
              if isinstance(value, Gated)}
    return stated.pop() if len(stated) == 1 else None


def _ran_apart(tests: list[str]) -> Path:
    """The directory a pytest process of its own wrote running `tests`: their records, their outcomes and its
    output (`apart_records`), kept until this process exits."""
    directory = Path(tempfile.mkdtemp(prefix="dew-mosaic-apart-"))
    atexit.register(shutil.rmtree, directory, ignore_errors=True)
    ran = subprocess.run([sys.executable, "-m", "pytest", *tests, "-q", "-p", "no:cacheprovider"],
                         cwd=Path(__file__).parent.parent,
                         env={**os.environ, apart_records.RECORDS: str(directory)},
                         capture_output=True, text=True, check=False)
    (directory / "output.txt").write_text(ran.stdout + ran.stderr)
    return directory


COMPILED: dict[str, dict] = {}
"""Each Mosaic GPU kernel's registers and spills as the GPU compiles its PTX (`_compiled_reports`), by its
module: Mosaic compiles a module once a process, so a later case of the same module prints no PTX
(`inherited`)."""


def inherited(kernel: dict, compiled: dict[str, dict]) -> dict:
    """`kernel`'s record (`mosaic_kernels`) with its registers and spills, their only source: as the GPU
    compiles its PTX, this compile's (`compiled`, by its name and launch, `report.launch_name`), which this
    process keeps by its module (`COMPILED`), or, where Mosaic compiled the same module before in this process
    and so printed no PTX, that compile's. Its binary is this process's compile, which may not be the GPU's
    (`RELOCATABLE`): a kernel neither covers keeps them unread."""
    name = report.launch_name(kernel["kernel"], kernel["launch"])
    if name in compiled:
        if kernel["module"] is not None:
            COMPILED[kernel["module"]] = compiled[name]
        return {**kernel, **compiled[name]}
    if kernel["module"] in COMPILED:
        return {**kernel, **COMPILED[kernel["module"]], "ptxas": "an earlier compile of its module"}
    unread = [*kernel["unread"], *(field for field in ("registers", "spills")
                                   if field not in kernel["unread"])]
    return {**kernel, "registers": None, "spilled": None, "unread": unread}


PTX: dict[str, str] = {}
"""Each Mosaic GPU module's PTX this process printed, by its module, as `COMPILED` keeps its compile: a later
compile of the same module prints none, and a least spill-free cap asked of it after (`_least`) reads this."""


BUILD_NVCC = {"cuda12": ("nvidia.cuda_nvcc", "12.9"), "cuda13": ("nvidia.cu13", "13.0")}
"""Each of JAX's CUDA builds (`dew._builds.CUDA_BUILDS`): the package of the nvcc wheel this environment
installs (locks/cpu.txt) and the release of the build's PTX compiler, which it must report: the CUDA release
the build's plugin was built against (Dew's JAX fork's .bazelrc, HERMETIC_CUDA_VERSION 13.0.0 and 12.9.1),
whose PTX compiler, linked into the plugin (Mosaic GPU's `GetAssemblyToBinaryCompilationProvider`:
libnvptxcompiler), compiles a Mosaic GPU kernel's PTX on a GPU running that build, whatever nvcc is installed
beside it: a B200 compiled with 13.0 where 13.4 held kernels 13.0 spilled (rows 5671, 5759)."""


@functools.cache
def ptxas_of(build: str) -> Path:
    """The ptxas that judges kernels as a GPU running JAX's CUDA `build` compiles them: its nvcc wheel's
    (`BUILD_NVCC`), refused unless its release is the build's PTX compiler's (`BUILD_NVCC`), naming the
    ptxas, its version and the build, so a relock that moves the wheel fails the gate rather than judging
    with another compiler."""
    package, release = BUILD_NVCC[build]
    found = importlib.util.find_spec(package)
    if found is None:
        raise RuntimeError(f"no {package} in this environment: the gate judges {build}'s GPUs' kernels with "
                           f"its ptxas, CUDA {release}'s")
    ptxas = Path(next(iter(found.submodule_search_locations or ()))) / "bin" / "ptxas"
    reported = subprocess.run([str(ptxas), "--version"], capture_output=True, text=True, check=False).stdout
    if f"release {release}," not in reported:
        version = reported.strip().splitlines()[-1] if reported.strip() else "no version"
        raise RuntimeError(f"{ptxas} ({version}) would judge the kernels of every GPU running {build}, which "
                           f"compiles them with CUDA {release}'s PTX compiler")
    return ptxas


def assemblers(generation: str) -> tuple[Path, ...]:
    """The ptxas of each CUDA build a GPU of `generation` runs (`generation_builds`, newest first), the gate
    judging its kernels under every one (`_compiled_reports`), its need scans reading the first's: a B200 runs
    the cuda13 build alone, whose PTX compiler held kernels 12.9 spilled 4 to 16 bytes of and spilled kernels
    12.9 held (rows 5671, 5759 and 5761)."""
    return tuple(ptxas_of(build) for build in generation_builds(generation))

RAISED = re.compile(r"setmaxnreg\.inc\.sync\.aligned\.u32 (\d+);")
"""A raise's registers (`RAISE`'s), as a kernel record states them (`raised`)."""
DECREASED = re.compile(r"setmaxnreg\.dec\.sync\.aligned\.u32 (\d+);")
"""A producer's decrease's registers, as a kernel record states them (`decreased`)."""


RELOCATABLE = not resources.RAISES_HONORED
"""Whether the GPU compiles a Mosaic GPU kernel's PTX relocatably, as jaxlib's Mosaic GPU does through
nvJitLink, where ptxas ignores a warpgroup's register raise (`resources.RAISES_HONORED`). The gate compiles
the PTX as the GPU does: a container without nvJitLink compiles Mosaic's whole-program, honoring raises the
GPU ignores."""


def _ptxas_text(ptx: str, generation: str, relocatable: bool, ptxas: Path | None = None) -> tuple[str, bool]:
    """ptxas's own report (`-v`) on the kernel `ptx` for the CUDA `generation`, compiled relocatably or
    whole-program (`_ptxas`) by `ptxas` (`assemblers`' first by default), and whether it took the kernel."""
    major, minor = capability(generation) or (0, 0)
    arch = f"sm_{major}{minor}{'a' if major >= 9 else ''}"
    with tempfile.NamedTemporaryFile("w", suffix=".ptx") as source:
        source.write(ptx)
        source.flush()
        relocating = ("--compile-only",) if relocatable else ()
        ran = subprocess.run([str(ptxas or assemblers(generation)[0]), f"-arch={arch}", "-v", *relocating,
                              source.name, "-o", os.devnull], capture_output=True, text=True, check=False)
    return ran.stdout + ran.stderr, ran.returncode == 0


def ptxas_notes(ptx: str, generation: str) -> str:
    """What ptxas says of the kernel `ptx` as the GPU compiles it (`RELOCATABLE`): its registers and spills,
    and the notes it makes of the code, a warpgroup MMA's serialization among them ("wgmma.mma_async
    instructions are serialized"), which the gate's registers and spills do not state."""
    return _ptxas_text(ptx, generation, RELOCATABLE)[0]


def _compiled_reports(directory: str, generation: str) -> dict[str, dict]:
    """Each kernel's registers a thread and spilled bytes as the GPU compiles the PTX Mosaic printed into
    `directory` (`_ptxas` at its own entry), by its name and launch (`report.launch_name`), the most of each
    under every CUDA build the gate judges the generation under (`assemblers`) and every build's notes: its
    binary is its compile in this process, which may not be the GPU's (`RELOCATABLE`)."""
    found = {}
    for path in Path(directory).glob("*.ptx"):
        reads = []
        for ptxas in assemblers(generation):
            text, took = _ptxas_text(path.read_text(), generation, RELOCATABLE, ptxas)
            if not took:
                raise RuntimeError(f"{ptxas} does not compile {path.name} for {generation}")
            reads.append(ptxas_read(text))
        worst = max(reads, key=lambda read: (read.spilled, read.registers))
        found[path.stem] = {"registers": worst.registers, "spilled": worst.spilled,
                            "losses": tuple(dict.fromkeys(code for read in reads for code in read.losses)),
                            "ptxas": "the GPU's compile of its PTX"}
    return found


def _compiled_here(cases, generation: str) -> list[dict]:
    """`compile_mosaic_kernels`' records, compiled in this process."""
    found: list[dict] = []
    for case in cases:
        # The program's own record (its error, or XLA's refusal of its block), its Mosaic kernels' reports the
        # evidence of their resources: a Triton launch line is none of theirs.
        models = dict(case.models or {})
        record: dict = {"name": case.name, "generation": generation,
                        "limit": gpu_target(generation).shared_limit,
                        "models": {name: model.record() for name, model in models.items()}}
        with tempfile.TemporaryDirectory(prefix="dew-mosaic-") as directory:
            _compiled(case, generation, record, directory)
            kernels = mosaic_kernels(record)
            # Each kernel's model its launch stated as it traced (`report.Launch.kernels`), whose producer
            # its schedule lowers to (`producer_failures`).
            record["stated_models"] = {
                report.launch_name(kernel["kernel"], kernel["launch"]): stated.record() for kernel in kernels
                if kernel["launch"] is not None and (launch := report.traced(kernel["launch"])) is not None
                and (stated := launch.kernels.get(kernel["kernel"])) is not None}
            compiled = _compiled_reports(directory, generation)
            record["kernels"] = [inherited(kernel, compiled) for kernel in kernels]
            printed = {path.stem: path.read_text() for path in Path(directory).glob("*.ptx")}
            for kernel in record["kernels"]:
                name = report.launch_name(kernel["kernel"], kernel["launch"])
                if kernel["module"] is not None and name in printed:
                    PTX[kernel["module"]] = printed[name]
                # The registers its consumers raise to, as its PTX states (`setmaxnreg.inc`); None where they
                # raise none or no PTX was printed for it.
                ptx = printed.get(name, PTX.get(kernel["module"], ""))
                kernel["raised"] = int(raise_.group(1)) if (raise_ := RAISED.search(ptx)) else None
                # The registers its producer lowers to, as its PTX states (`setmaxnreg.dec`); None likewise.
                kernel["decreased"] = int(lower.group(1)) if (lower := DECREASED.search(ptx)) else None
        record["tmem_limit"] = gpu_target(generation).tmem_columns or 0
        found.append(record)
    return found


def mosaic_failures(found: list[dict]) -> list[str]:
    """Compile errors, spills, missing or excessive shared/TMEM allocations, a launch its lowering did not
    certify (`report.certified`), and a producer its schedule lowers to other registers than its model
    states (`setmaxnreg.dec` against `RegisterModel.producer`: a launch's plan and its emission one fact).
    Whether a launch's registers hold is its certification's alone: the gate judges no register model."""
    failed = failures(found)
    for record in found:
        if refused(record):
            continue
        failed += [f"{record['name']}: a launch not certified, {why}"
                   for why in record.get("uncertified", ())]
        if not record["kernels"]:
            failed.append(f"{record['name']}: no Mosaic GPU kernel compiled")
        for kernel in record.get("kernels", ()):
            found_kernel = _report(kernel)
            if (why := found_kernel.failure(record["limit"], record["tmem_limit"])) is not None:
                failed.append(f"{record['name']} {found_kernel.kernel}: {why}")
            stated = record.get("models", {}).get(found_kernel.kernel)
            if stated is not None and stated["shared"] not in (None, found_kernel.shared):
                failed.append(f"{record['name']} {found_kernel.kernel}: its planner sized {stated['shared']} "
                              f"bytes of shared memory, the kernel asks for {found_kernel.shared}")
    return failed + producer_failures(found)


def producer_failures(found: list[dict]) -> list[str]:
    """Each kernel whose schedule lowers its producer to other registers than its model states, or none where
    its model states a producer whose program moves registers, or lowers it where its program moves none
    (`setmaxnreg.dec`, the record's `decreased`, against `RegisterModel.producer` and `moves`): a launch's
    plan and its emission one fact."""
    failed = []
    for record in found:
        for kernel in record.get("kernels", ()):
            found_kernel = _report(kernel)
            stated = record.get("stated_models", {}).get(found_kernel.traced,
                                                          record.get("models", {}).get(found_kernel.kernel))
            if stated is None or not stated["producer"]:
                continue
            lowered = stated["producer"] if stated.get("moves", True) else None
            if kernel.get("decreased") != lowered:
                failed.append(f"{record['name']} {found_kernel.kernel}: its schedule lowers its producer to "
                              f"{kernel.get('decreased')} registers, its model {lowered}")
    return failed


def compiled_kernels(record: dict) -> set[str]:
    """The names of the kernels `record` compiled, as its models name them (`Report.kernel`)."""
    return {_report(kernel).kernel for kernel in record.get("kernels", ())}


def _report(kernel: dict) -> Report:
    stated = {field.name: kernel[field.name] for field in dataclasses.fields(Report)
              if field.name in kernel}
    return Report(**{**stated, "unread": tuple(kernel["unread"])})


TPU_TOPOLOGIES = {"v5e": "v5e:2x2", "v6e": "v6e:2x2"}
"""The compile-only topology of each TPU generation the gate compiles for: libtpu describes a host's
chips (2x2), of which a case takes one."""


@functools.cache
def _tpu_device(generation: str) -> Mesh:
    """A one-device mesh of a compile-only TPU of `generation`."""
    topology = topologies.get_topology_desc(TPU_TOPOLOGIES[generation], "tpu")
    return Mesh(np.array(topology.devices[:1]), ("data",))


def compile_tpu_kernels(cases, generation: str) -> list[dict]:
    """Each case compiled by libtpu for a compile-only TPU of `generation`, traced under its abstract mesh
    so a kernel's `get_tpu_info` reads that TPU: its name and generation, or the error, Mosaic's refusal
    of a kernel past its stated VMEM limit included."""
    mesh = _tpu_device(generation)
    replicated = NamedSharding(mesh, PartitionSpec())
    # The generation assumed as well as its mesh, so a kernel's facts are its target's
    # (`dew.nn.kernels.splash.block_sizes`' scoped VMEM).
    found: list[dict] = []
    for case in cases:
        record: dict = {"name": case.name, "generation": generation}
        found.append(record)
        fn, args = case.call()
        placed = jax.tree.map(lambda leaf: jax.ShapeDtypeStruct(leaf.shape, leaf.dtype, sharding=replicated)
                              if isinstance(leaf, jax.ShapeDtypeStruct) else leaf, args)
        try:
            with assumed(generation), jax.sharding.use_abstract_mesh(mesh.abstract_mesh):
                lowered = jax.jit(fn).trace(*placed).lower()
            lowered.compile()
        except Exception as error:  # A case that does not lower or compile is its own failure.
            # Mosaic TPU's refusal leads with its reason and ends with diagnostics: both ends kept.
            text = str(error)
            text = text if len(text) <= 1600 else f"{text[:800]} ... {text[-800:]}"
            record["error"] = f"{type(error).__name__}: {text}"
    return found


class Uncounted(grouped_matmul.MosaicGmm):
    """The grouped forward with a register model that counts nothing, so its derivation takes a tile its
    registers do not hold: a launch whose model misses. Its first tile is a paired product's widest, 128 x
    256, two accumulators of 128 registers a thread, which spills in every compile whatever its walk's
    addresses take (the paired 128 x 128 tile this launch took first spilled 16 bytes in the process's own
    compile only while its walk held a stage's addresses in registers, and none since the walk forms them
    where it uses them: `rings.opaque`); a narrower tile comes once a compile has refused a tile of its
    launch (`report.refused_launches`, the relowering's proposals included)."""

    def registers(self, ba, config):
        return 0

    def candidate(self, ba, config, target):
        return super().candidate(ba, config, target) and (
            config.block_n == 256 or bool(report.refused_launches()))
