MOSAIC_REFUSED = re.compile(r"smem_bytes=(\d+) > max_smem_bytes=\d+")
"""Mosaic GPU's refusal, as it lowers, of a kernel whose shared memory a block of the GPU does not hold."""

SHARED = re.compile(r"smem_scratch_bytes=(\d+)")
TENSOR_MEMORY = re.compile(r"tmem_scratch_cols=(\d+), tmem_collective_scratch_cols=(\d+)")
"""A Mosaic GPU kernel's resource estimate as Pallas prints it while it lowers the kernel (its `Resources`,
under MOSAIC_GPU_DUMP_RESOURCES)."""
PTX_MODULE = "// Generated by LLVM NVPTX Back-End"
"""The first line but one of each PTX module Mosaic GPU prints while it compiles (MOSAIC_GPU_DUMP_PTX)."""
PTX_ENTRY = re.compile(r"\.entry\s+([A-Za-z_$][\w$]*)")
"""A PTX module's kernel function, `<kernel>_mosaic_gpu_kernel` (`report.KERNEL_FUNCTION`)."""
REGISTERS = re.compile(r"Used (\d+) registers")
SPILLS = re.compile(r"(\d+) bytes spill stores, (\d+) bytes spill loads")
LOSSES = {"C7507": "ignores its setmaxnreg, its warp roles' paths rejoining after the split",
          **{f"C751{digit}": "serializes its warpgroup MMAs" for digit in range(6)}}
"""ptxas's notes of a performance loss the gate fails a kernel for, by code: its register raises and decreases
dropped, the threads left at the entry's registers (C7507, the kernel challenge's notes/ptxas-re.md §4), or
its warpgroup MMAs serialized, each HGMMA waited for before the next issues (C7510 to C7515)."""
LOSS = re.compile(r"\((C75\d\d)\) Potential Performance Loss: ")
"""A note of ptxas's of a performance loss, `ptxas_read`."""


@dataclasses.dataclass(frozen=True)
class Assembled:
    """What ptxas reports of a kernel (`ptxas_read`): its registers a thread, its spilled bytes, and the codes
    of each note of a performance loss the gate fails it for (`LOSSES`)."""
    registers: int
    spilled: int
    losses: tuple[str, ...]


def ptxas_read(text: str) -> Assembled:
    """ptxas's report `text` of a kernel read: the most registers and spilled bytes it states, and its
    serialization notes' codes in order."""
    used = [int(count) for count in REGISTERS.findall(text)]
    spilled = [int(stores) + int(loads) for stores, loads in SPILLS.findall(text)]
    return Assembled(max(used, default=0), max(spilled, default=0),
                     tuple(code for code in LOSS.findall(text) if code in LOSSES))


@dataclasses.dataclass(frozen=True)
class Report:
    """One Mosaic GPU kernel's reports: its name, the shared bytes and tensor memory columns it asks for
    (its binary's launch and Mosaic's resource estimate, respectively), its registers a thread and its
    spilled bytes as the GPU compiles its PTX
    (`inherited`, their only source: None until it reads them), what the reports left `unread`: a kernel no
    binary carries, or a field no report states, is no evidence the kernel is within its resources; and its
    `module`, its kernel hash, which two compiles of one module share: Mosaic compiles a module once a
    process, so a later compile of it prints no PTX of its own; the digest of the launch that traced it
    (`launching`), which its name carried, or None; ptxas's notes of a performance loss it fails for
    (`ptxas_read`, `LOSSES`); and what its machine code breaks of the SASS rules (`report.sass_findings`,
    read where nvdisasm is installed)."""
    kernel: str
    shared: int | None
    tmem: int | None
    registers: int | None
    spilled: int | None
    unread: tuple[str, ...] = ()
    module: str | None = None
    launch: str | None = None
    losses: tuple[str, ...] = ()
    sass: tuple[str, ...] = ()

    @property
    def traced(self) -> str:
        """The kernel's name with its launch's (`report.launch_name`), which keys its evidence."""
        return report.launch_name(self.kernel, self.launch)

    def failure(self, shared_limit: int, tmem_limit: int) -> str | None:
        """Why the kernel is not within a multiprocessor's `shared_limit` bytes and `tmem_limit` tensor memory
        columns without spilling registers, with its warpgroup MMAs in flight together and its register raises
        taken, or None where it is: a kernel ptxas serializes runs its MMAs one at a time, its registers and
        spills clean (row 3615; the kernel challenge's C7511 at 112 registers, C7512 at 96), and one whose
        raises it ignores keeps its consumers at the entry's registers (C7507, row 4071)."""
        if self.unread:
            return f"its reports state no {', '.join(self.unread)}"
        if self.losses:
            return "ptxas " + "; ".join(f"{LOSSES[code]} ({code})" for code in self.losses)
        if self.sass:
            return "its machine code holds " + "; ".join(self.sass)
        if (self.shared is not None and self.tmem is not None and self.shared <= shared_limit
                and self.tmem <= tmem_limit and self.spilled == 0):
            return None
        return (f"{self.shared} shared bytes (limit {shared_limit}), {self.tmem} tensor memory columns "
                f"(limit {tmem_limit}), {self.spilled} bytes spilled")


def reports(estimates: dict[str, str], binaries: list[report.Binary],
            modules: dict[str, str] | None = None) -> list[Report]:
    """Each kernel's `Report` of its total shared memory from its binary (`binaries`, `report.binaries`)
    and tensor memory from its resource estimate (`estimates`, Pallas's printed `Resources`, its module's,
    `_estimates`), paired by the kernel's name and launch (`report.launch_name`), with its module
    (`modules`, its kernel hash): its registers and spills are its PTX's as the GPU compiles it
    (`inherited`). An estimate past the shared memory its binary's launch asks for, or none where it asks
    for some, is another kernel's, and raises, as two binaries of one launch do."""
    found: dict[str, report.Binary] = {}
    for binary in binaries:
        if found.setdefault(report.launch_name(binary.kernel, binary.launch), binary) != binary:
            raise ValueError(f"two binaries of {report.launch_name(binary.kernel, binary.launch)}")
    found_reports = []
    for name in sorted(set(estimates) | set(found)):
        text, binary = estimates.get(name, ""), found.get(name)
        shared, tmem = SHARED.search(text), TENSOR_MEMORY.search(text)
        if shared and binary is not None and binary.shared is not None and not (
                int(shared.group(1)) <= binary.shared and (int(shared.group(1)) > 0 or binary.shared == 0)):
            raise ValueError(f"{name}'s estimate of {shared.group(1)} shared bytes pairs with a binary whose "
                             f"launch asks for {binary.shared}: the estimate is another kernel's")
        # A kernel no binary carries is no compiled kernel, whatever its PTX's compile says.
        unread = tuple(field for field, read in (
            ("shared bytes", shared is not None and binary is not None and binary.shared is not None),
            ("tensor memory columns", tmem), ("binary", binary),
            ("machine code", binary is None or binary.sass is not None)) if not read)
        kernel, launch = report.kernel_of(name)
        found_reports.append(Report(
            kernel, binary.shared if binary is not None else None,
            sum(map(int, tmem.groups())) if tmem else None,
            None, None, unread, (modules or {}).get(name), launch,
            sass=tuple(binary.sass or ()) if binary is not None else ()))
    return found_reports


UNIQUIFIED = re.compile(r"__\d+$")
"""The suffix XLA gives a kernel name's later launches in a program (`recurrence_cumulated__1`)."""


@functools.cache
def staged_copy(shape: tuple[int, ...], dtype):
    """A Mosaic GPU kernel copying its operand through shared memory by TMA: the least Mosaic kernel a test
    compiles for a generation."""
    from jax.experimental.pallas import mosaic_gpu as plgpu

    def body(source, out, staged, barrier):
        plgpu.copy_gmem_to_smem(source, staged, barrier.at[0])
        plgpu.barrier_wait(barrier.at[0])
        plgpu.copy_smem_to_gmem(staged, out)
        plgpu.wait_smem_to_gmem(0)

    return plgpu.kernel(body, out_type=jax.ShapeDtypeStruct(shape, dtype), num_threads=1, thread_name="wg",
                        scratch_types=[plgpu.SMEM(shape, dtype), plgpu.Barrier(num_barriers=1)])


class Expected(NamedTuple):
    """What a public route's program shows compiled for a mesh of its GPUs (a case's `expected`): the mesh
    (`axes`, each axis's devices), each positional argument's placement on it (`specs`, a `PartitionSpec`
    each, None replicated), the launches it runs (`launches`, its kernel calls' names), an array a device's
    call of a launch reads (`shards`, by launch: some call of it reads an operand of this shape, a shard's
    where it runs per shard), and every collective it moves or sums by (`collectives`, each `(op, mesh
    axes)`: exactly these, `sharded.collective_axes` of its compiled program). A case missing any of them,
    or showing others, fails (`route_failures`)."""

    axes: tuple[tuple[str, int], ...]
    specs: tuple
    launches: frozenset[str]
    shards: Mapping[str, tuple[int, ...]] = MappingProxyType({})
    collectives: frozenset[tuple[str, frozenset[str]]] = frozenset()


def _device(generation: str, axes: tuple[tuple[str, int], ...] = (("data", 1),)) -> Mesh:
    """A mesh of compile-only devices of `generation`, of `axes` (one device's by default)."""
    sizes = tuple(size for _, size in axes)
    devices = compile_only_gpus(generation, count=int(np.prod(sizes)))
    return Mesh(np.array(devices).reshape(sizes), tuple(name for name, _ in axes))


def lowered_for(fn, args, generation: str, expected: Expected | None = None):
    """`fn` traced on `args`, its abstract leaves placed on compile-only devices of the CUDA `generation`
    (`_device`: one, replicated, or `expected`'s mesh, each argument by its spec), and lowered as on that GPU
    (`assumed`, the mesh's abstract devices) within its block's shared memory: what XLA compiles for it,
    never run."""
    mesh = _device(generation) if expected is None else _device(generation, expected.axes)
    specs = (None,) * len(args) if expected is None else expected.specs
    def placed_on(arg, sharding: NamedSharding):
        return jax.tree.map(lambda leaf: jax.ShapeDtypeStruct(leaf.shape, leaf.dtype, sharding=sharding)
                            if isinstance(leaf, jax.ShapeDtypeStruct) else leaf, arg)

    placed = tuple(placed_on(arg, NamedSharding(mesh, spec or PartitionSpec()))
                   for arg, spec in zip(args, specs, strict=True))
    # Deviceless Mosaic lowering defaults to Hopper's limit, not this target's.
    # Its bound checks the total allocation, including barriers outside the scratch estimate.
    with (assumed(generation), jax.sharding.use_abstract_mesh(mesh.abstract_mesh),
          mgpu_core.artificial_shared_memory_limit(gpu_target(generation).shared_limit)):
        return jax.jit(fn).trace(*placed).lower()


def refused(record: dict) -> bool:
    """Whether a compiled record failed as a program: its error, or shared bytes past its block's limit
    (a Triton kernel's, or XLA's refusal of a block, which a Mosaic GPU program states only then)."""
    return "error" in record or ("shared" in record and record["shared"] > record["limit"])


def failures(found: list[dict]) -> list[str]:
    """Each compiled record's failure, if any: its error, or its shared bytes past its block's limit."""
    return [f"{record['name']}: {record['error']}" if "error" in record else
            f"{record['name']}: {record['shared']} shared bytes, limit {record['limit']}"
            for record in found if refused(record)]


def compile_kernels(cases, generation: str) -> list[dict]:
    """Each case (`name`, `call()` giving the kernel and abstract operands) on the CUDA `generation`,
    lowered as on that GPU on this host (`assumed`, `lowered_for`) and compiled by XLA for a compile-only
    device of it, never run: its name, the generation's block limit, and the shared bytes its Triton
    kernels launch with (the most of any; those XLA refused, where it refused one), or the error.

    A cheap first filter: a kernel that does not compile or takes more shared memory than its GPU's
    block holds fails here as it would there, before a GPU is paid for. A program whose executable carries
    no Triton kernel fails too: nothing states its kernel's shared bytes (`triton_evidence`)."""
    found: list[dict] = []
    for case in cases:
        record: dict = {"name": case.name, "generation": generation,
                        "limit": gpu_target(generation).shared_limit}
        found.append(record)
        compiled = _compiled(case, generation, record)
        if compiled is None:
            continue
        launched, calls = compiled
        record.update(triton_evidence(calls, launched))
    return found


def triton_evidence(calls: dict[str, int], launched: list[tuple[str, int]]) -> dict:
    """What a program's executable says of its Triton kernels (`launched`, `report.launched_kernels`: each
    custom kernel it launches by name, with the shared bytes its launch asks), its calls by name with the
    call sites of each (`calls`, the lowering reader's `triton_kernels`, which owns the inventory): the
    largest shared bytes a call launches with, or why it says nothing. Each Triton call launches a kernel of
    its own, named as the call is, XLA numbering a name's later calls (recurrence_cumulated__1); a call with
    no such launch, or a program that calls no Triton kernel, is no evidence its kernel compiled within its
    block (row 1381). The executable's, not XLA's dumped thunk sequence, which a GPU host's run omitted
    (IG-FINAL3: every Triton decode compile cell)."""
    launches: dict[str, list[int]] = {}
    for name, shared in launched:
        launches.setdefault(UNIQUIFIED.sub("", name), []).append(shared)
    if not calls:
        return {"error": "XLA's program calls no Triton kernel"}
    unlaunched = sorted(name for name, count in calls.items() if len(launches.get(name, ())) < count)
    if unlaunched:
        return {"error": f"no launch of its own states the shared bytes of {', '.join(unlaunched)}"}
    return {"shared": max(size for name in calls for size in launches[name])}


def _compiled(case, generation: str, record: dict,
              directory: str | None = None) -> tuple[list[tuple[str, int]], dict[str, int]] | None:
    """`case` lowered as on the CUDA `generation` (`lowered_for`) and compiled by XLA for a
    compile-only device of it: the custom kernels its executable launches (`report.launched_kernels`) and
    the lowered program's Triton calls by name
    (`triton_kernels`), or None, `record` holding why: the error, or the shared bytes of a block XLA
    refused. `record['modules']` holds each Mosaic GPU kernel's module (its kernel hash) by its name and
    launch, and `record['certified']` each one certification compiled alone in the process
    (`report.certifications`). Given a `directory`, its Mosaic GPU kernels' evidence too (`_printed`):
    `record['estimates']` each one's resource estimate Pallas prints as it lowers, `record['binaries']` each
    one's binary (`report.binaries`), and in `directory` the PTX Mosaic prints as it compiles, a
    `<kernel>.ptx` each."""
    fn, args = case.call()
    expected = getattr(case, "expected", None)
    # Each launch's derived config is certified as it traces, as a start on the GPU certifies it
    # (`report.certified`), on a compile-only device of the generation: its kernels compiled then, each
    # module once a process, so their PTX prints as the program lowers, not as it compiles. Here, in the
    # process of the generation's capability (`compile_mosaic_kernels`), never in a bare lowering.
    estimating = (_printed(MOSAIC_GPU_DUMP_RESOURCES="1", MOSAIC_GPU_DUMP_PTX="1") if directory
                  else contextlib.nullcontext([]))
    uncertified = report.uncertified()
    try:
        with estimating as estimated, report.certifying(compile_only_gpus(generation)[0]):
            lowered = lowered_for(fn, args, generation, expected)
    except Exception as error:  # A case that does not lower is its own failure.
        # One a block's shared memory does not hold asks its bytes, as XLA's refusal of a Triton kernel does.
        refused = MOSAIC_REFUSED.search(str(error))
        if refused is None:
            record["error"] = f"it does not lower: {str(error)[-800:]}"
        else:
            record["shared"] = int(refused.group(1))
        return None
    # A launch the lowering could not certify (`report.certified`) is a failure of its own: its run would
    # find its spills only as its whole program compiles.
    record["uncertified"] = [f"{type(key[0]).__name__ if not isinstance(key[0], str) else key[0]} at "
                             f"{key[1]}: {why}" for key, why in report.uncertified().items()
                             if key not in uncertified]
    # Each kernel once, as JAX lowered it (a function's kernels however many calls reach them).
    calls = [call for call in kernel_calls(lowered, unrun=True) if call.kind == "mosaic_gpu"]
    modules = kernel_modules(calls)
    record["modules"] = modules
    # Each kernel certification compiled alone in this process, by name and launch: its module.
    record["certified"] = {name: module for found in report.certifications()
                           for name, (module, _) in found.kernels.items()}
    if directory is not None:
        record["estimates"] = _estimates(calls, "".join(estimated))
    # A process whose persistent compilation cache is on keeps it on here (JAX settles that once a
    # process): a compile-only device's entry reads back as unloadable, with a warning, and compiles.
    printing = _printed(MOSAIC_GPU_DUMP_PTX="1") if directory else contextlib.nullcontext([])
    try:
        with printing as printed:
            executable = lowered.compile()
    except jax.errors.JaxRuntimeError as error:
        asked = report.shared_asked(error)
        if asked is None:
            record["error"] = f"XLA does not compile it: {str(error)[-800:]}"
        else:
            record["shared"] = asked
        return None
    if directory is not None:
        record["binaries"] = [dataclasses.asdict(found)
                              for found in report.binaries(executable, decoded=True)]
        write_modules("".join(estimated), "".join(printed), directory, modules)
    if expected is not None:
        record["route"] = _route(lowered, executable, _device(generation, expected.axes))
    return report.launched_kernels(executable), triton_kernels(lowered)


def kernel_modules(calls: list) -> dict[str, str]:
    """Each Mosaic GPU call's module (its kernel hash) by its kernel's name and launch (`report.launch_name`):
    one name and launch of two modules raises, as its evidence would be one's."""
    modules: dict[str, str] = {}
    for call in calls:
        name = report.launch_name(call.name, call.launch)
        if modules.setdefault(name, call.config) != call.config:
            raise ValueError(f"{name} names two kernels: its evidence would be one's")
    return modules


def _estimates(calls: list, printed: str) -> dict[str, str]:
    """Each Mosaic GPU call's resource estimate by its kernel's name and launch (`report.launch_name`), from
    what its lowering printed: Mosaic prints one each time it builds a kernel's module, beside the hash that
    names its kernel (`<name> <hash> Resources(...)`), which a call's `config` holds (its first 16 hex
    digits). A module built once and reused (a lowering JAX cached, a launch certified as it traced,
    `report.certified`) prints one, its estimate kept by its module (`ESTIMATES`)."""
    for name, hashed, estimate in PRINTED_ESTIMATE.findall(printed):
        del name
        ESTIMATES[hashed[:16]] = estimate
    return {report.launch_name(call.name, call.launch): ESTIMATES[call.config] for call in calls
            if call.config in ESTIMATES}


PRINTED_ESTIMATE = re.compile(r"^(\S+) ([0-9a-f]{64}) (Resources\(.*\))$", re.M)
"""A Mosaic GPU kernel's resource estimate as it prints it (`core.py`'s dump: its module's name, its kernel's
hash and the estimate)."""


ESTIMATES: dict[str, str] = {}
"""Each Mosaic GPU kernel's resource estimate this process read, by its module (its kernel hash)."""


def write_modules(lowering: str, compiling: str, directory: str, kernels: Collection[str]) -> None:
    """Each PTX module of the program's `kernels` (by name and launch, `report.launch_name`) Mosaic printed
    (`PTX_MODULE`) into `directory` as `<kernel>.ptx`, its kernel's name and launch its entry's
    (`report.kernel_of`): one certification assembled as the program lowered (`report.certified`), which its
    compile reuses, or one its compile assembled. A module the compile assembled supersedes certification's
    of its name and launch, which the program does not run (a gradient's forward is another kernel than the
    one certified, the recurrence template's); one of no kernel of the program is a config certification
    refused. Two modules of one name and launch in one print raise."""
    modules: dict[str, str] = {}
    for printed in (lowering, compiling):
        assembled: dict[str, str] = {}
        for part in printed.split(PTX_MODULE)[1:]:
            entry = PTX_ENTRY.search(part)
            if entry is None:
                raise ValueError(f"a printed PTX module names no entry: {part[:200]}")
            name = report.launch_name(*report.kernel_of(entry.group(1)))
            if name in assembled:
                raise ValueError(f"two PTX modules of {name}")
            assembled[name] = part
        modules.update(assembled)
    for name, part in modules.items():
        if name in kernels:
            Path(directory, f"{name}.ptx").write_text("//\n" + PTX_MODULE + part)


def _route(lowered, executable, mesh: Mesh) -> dict:
    """What a compiled route shows (`Expected`): its launches by name, the operands each of their calls
    reads, and its collectives over `mesh`, JSON's types (a record a process of its own writes back). Its
    launches are those a run of it reaches (`kernel_calls`), not a loop's of no trips, which the resource
    compile reads all the same (`unrun`): a route whose launch never runs does not take it."""
    calls = kernel_calls(lowered)
    shards: dict[str, list] = {}
    for call in calls:
        shards.setdefault(call.name, []).append([list(shape) for shape in call.operands])
    return {"launches": sorted(shards), "shards": shards,
            "collectives": sorted([op, sorted(axes)]
                                  for op, axes in collective_axes(executable.as_text(), mesh))}


def route_failures(cases, found: list[dict]) -> list[str]:
    """Each routed case (its `expected`) whose compiled program misses a launch it states, reads no shard it
    states in any call of a launch, or moves or sums by collectives other than the plan's, or that left no
    program to read: the route's own evidence, beside its kernels' resources."""
    failed = []
    for case, record in zip(cases, found, strict=True):
        if (expected := getattr(case, "expected", None)) is None:
            continue
        if (route := record.get("route")) is None:
            why = record.get("error", "none")
            failed.append(f"{case.name}: no compiled program states its route ({why})")
            continue
        if missing := sorted(expected.launches - set(route["launches"])):
            failed.append(f"{case.name}: no launch of {', '.join(missing)} (it ran {route['launches']})")
        for name, shape in expected.shards.items():
            calls = route["shards"].get(name, [])
            if not any(list(shape) in operands for operands in calls):
                failed.append(f"{case.name}: no call of {name} reads a {list(shape)} shard "
                              f"(its calls read {calls})")
        collectives = {(op, frozenset(axes)) for op, axes in route["collectives"]}
        if collectives != expected.collectives:
            failed.append(f"{case.name}: collectives {sorted(map(_named, collectives))}, where its plan "
                          f"states {sorted(map(_named, expected.collectives))}")
    return failed


def _named(collective: tuple[str, frozenset[str]]) -> str:
    """A collective as a failure names it: its op over its axes."""
    op, axes = collective
    return f"{op} over {'/'.join(sorted(axes)) or 'no axis'}"


def mosaic_kernels(record: dict) -> list[dict]:
    """Each Mosaic GPU kernel's report from `record`'s evidence (`reports`, `_compiled`), as a record a test's
    process of its own writes back as JSON (`compile_mosaic_kernels`)."""
    binaries = [report.Binary(**found) for found in record.get("binaries", ())]
    return [dataclasses.asdict(found) for found in
            reports(record.get("estimates", {}), binaries, record.get("modules"))]


