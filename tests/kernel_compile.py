MOSAIC_REFUSED = re.compile(r"smem_bytes=(\d+) > max_smem_bytes=\d+")
"""Mosaic GPU's refusal, as it lowers, of a kernel whose shared memory a block of the GPU does not hold."""

SHARED = re.compile(r"smem_scratch_bytes=(\d+)")
TENSOR_MEMORY = re.compile(r"tmem_scratch_cols=(\d+), tmem_collective_scratch_cols=(\d+)")
"""A Mosaic GPU kernel's resource estimate as Pallas prints it while it lowers the kernel (its `Resources`,
under MOSAIC_GPU_DUMP_RESOURCES)."""
PTX_MODULE = "// Generated by LLVM NVPTX Back-End"
"""The first line but one of each PTX module Mosaic GPU prints while it compiles (MOSAIC_GPU_DUMP_PTX)."""
PTX_ENTRY = re.compile(r"\.entry\s+([A-Za-z_$][\w$]*)")
"""A PTX module's kernel function, `<kernel>_mosaic_gpu_kernel` (`assembled.KERNEL_FUNCTION`)."""
REGISTERS = re.compile(r"Used (\d+) registers")
SPILLS = re.compile(r"(\d+) bytes spill stores, (\d+) bytes spill loads")
LOSSES = assembled.SERIALIZED | {assembled.IGNORED_RAISE}
"""ptxas's notes of a performance loss the gate fails a kernel for, as assembled.py states them: its
warpgroup MMAs serialized (`assembled.SERIALIZED`, which a run refuses too), or its setmaxnreg ignored, its
roles left at the entry's registers (`assembled.IGNORED_RAISE`, a derived kernel's structure the gate
holds)."""
LOSS = re.compile(r"\((C75\d\d)\) Potential Performance Loss: ")
"""A note of ptxas's of a performance loss, `ptxas_read`."""


@dataclasses.dataclass(frozen=True)
class Assembled:
    """What ptxas reports of a kernel (`ptxas_read`): its registers a thread, its spilled bytes, and the codes
    of each note of a performance loss the gate fails it for (`LOSSES`)."""
    registers: int
    spilled: int
    losses: tuple[str, ...]


def ptxas_read(text: str) -> Assembled:
    """ptxas's report `text` of a kernel read: the most registers and spilled bytes it states, and its
    serialization notes' codes in order."""
    used = [int(count) for count in REGISTERS.findall(text)]
    spilled = [int(stores) + int(loads) for stores, loads in SPILLS.findall(text)]
    return Assembled(max(used, default=0), max(spilled, default=0),
                     tuple(code for code in LOSS.findall(text) if code in LOSSES))


@dataclasses.dataclass(frozen=True)
class Report:
    """One Mosaic GPU kernel's reports: its name, the shared bytes and tensor memory columns it asks for (its
    binary's launch and Mosaic's resource estimate, respectively), its registers a thread and its spilled
    bytes as the GPU compiles its PTX, else its binary's (`inherited`: None until it reads them), what the
    reports left `unread`: a kernel no binary carries, or a field no report states, is no evidence the kernel
    is within its resources; and its `module`, its kernel hash, which two compiles of one module share: Mosaic
    compiles a module once a process, so a later compile of it prints no PTX of its own; the digest its name
    carries, its kernel's identity within the launch that traced it (`report.named`), or None; ptxas's notes
    of a performance loss it fails for (`ptxas_read`, `LOSSES`); and what its machine code breaks of the SASS
    rules (`sass.sass_findings_of`, read where nvdisasm is installed)."""
    kernel: str
    shared: int | None
    tmem: int | None
    registers: int | None
    spilled: int | None
    unread: tuple[str, ...] = ()
    module: str | None = None
    launch: str | None = None
    losses: tuple[str, ...] = ()
    sass: tuple[str, ...] = ()
    launched: str | None = None
    """The digest of the launch that traced it (`assembled.Binary.launched`), None where no binary carries
    it."""
    binary_registers: int | None = None
    binary_spilled: int | None = None
    binary_losses: tuple[str, ...] = ()
    """The codes of the notes of a performance loss its binary carries (`assembled.Binary.notes`, what the
    plugin's own ptxas noted as it assembled the kernel, `LOSSES`), beside the gate's own read of its PTX's
    (`losses`)."""
    """Its registers a thread and the bytes it spills as its executable's binary carries them
    (`assembled.Binary`): this process's assembly, which `inherited` reads where no PTX of it was dumped."""
    threads: int | None = None
    decreased: int | None = None
    raised: int | None = None
    """Its threads a block, the registers its producer lowers to and its consumers raise to, as its binary
    states them (`assembled.Binary`: its `.nv.info` and its machine code's USETMAXREG), its program's facts
    whatever assembler made it; None where it states none (a launch of no producer, or no disassembler)."""
    cap: int | None = None
    """The registers its launch runs a thread at, as its compile states them (`_compiled_here`'s), None where
    unstated: a Mosaic kernel whose registers are read and whose cap is not fails (`failure`, row 6670); a
    Triton kernel's launch states none."""
    kind: str = "mosaic_gpu"
    """The compiler that produced the binary (`assembled.Binary.kind`: `mosaic_gpu` or `triton`)."""
    planned: bool = True
    """Whether a launch plan states the kernel's resources, which the gate holds its binary to: its register
    cap, its planner's shared bytes and its producer's registers, and the PTX the gate compiles it from (a
    Mosaic GPU kernel's); a Pallas-Triton kernel's compile picks them, its cubin's own its whole evidence,
    read as `reports` makes it (row 9719: each consumer branched on `kind`)."""
    index: str | None = None
    """XLA uniquification suffix (`assembled.Binary.index`) where a second cubin shares `(kernel, launch)`."""

    @property
    def traced(self) -> str:
        """The kernel's name with its launch's (`assembled.launch_name`), which keys its evidence."""
        return assembled.launch_name(self.kernel, self.launch)

    def failure(self, shared_limit: int, tmem_limit: int) -> str | None:
        """Why the kernel is not within a multiprocessor's `shared_limit` bytes and `tmem_limit` tensor memory
        columns without spilling registers, within its launch's register cap (`cap`), with its warpgroup MMAs
        in flight together and its register raises taken, or None where it is: a kernel ptxas serializes runs
        its MMAs one at a time, its registers and spills clean (row 3615; the kernel challenge's C7511 at 112
        registers, C7512 at 96), and one whose raises it ignores keeps its consumers at the entry's registers
        (C7507, row 4071)."""
        if self.unread:
            return f"its reports state no {', '.join(self.unread)}"
        if self.losses:
            return "ptxas " + "; ".join(
                ("ignores its setmaxnreg" if code == assembled.IGNORED_RAISE
                 else "serializes its warpgroup MMAs") + f" ({code})" for code in self.losses)
        if self.sass:
            return "its machine code holds " + "; ".join(self.sass)
        if self.registers is not None and self.cap is None and self.planned:
            # A planned kernel's with no thread count and no raise: its allocation judged against nothing (row
            # 6670).
            return f"its reports state no register cap its launch runs at for its {self.registers} registers"
        if self.registers is not None and self.cap is not None and self.registers > self.cap:
            return f"{self.registers} registers a thread, above its launch's {self.cap}"
        if (self.shared is not None and self.tmem is not None and self.shared <= shared_limit
                and self.tmem <= tmem_limit and self.spilled == 0):
            return None
        return (f"{self.shared} shared bytes (limit {shared_limit}), {self.tmem} tensor memory columns "
                f"(limit {tmem_limit}), {self.spilled} bytes spilled")


def reports(estimates: dict[str, str], binaries: list[assembled.Binary],
            modules: dict[str, str] | None = None) -> list[Report]:
    """Each kernel's `Report` of its total shared memory from its binary (`binaries`, `assembled.binaries`)
    and tensor memory from its resource estimate (`estimates`, Pallas's printed `Resources`, its module's,
    `_estimates`), paired by the kernel's name and launch (`assembled.launch_name`), with its module
    (`modules`, its kernel hash): its registers and spills are its PTX's as the GPU compiles it
    (`inherited`), or, for a Pallas-Triton template binary (`Binary.kind == "triton"`), its cubin's own
    shared memory, registers and stack frame (row 7263: Triton prints no Mosaic resource estimate or PTX;
    TMEM is 0 only where its decoded SASS proves `uses_tmem is False`). An estimate past the shared memory
    its binary's launch asks for, or none where it asks for some, is another kernel's, and raises, as two
    binaries of one launch do."""
    mosaic_found: dict[str, assembled.Binary] = {}
    triton_found: dict[str, assembled.Binary] = {}
    for binary in binaries:
        if binary.kind == "triton":
            key = assembled.launch_name(binary.kernel, binary.launch, binary.index)
            if triton_found.setdefault(key, binary) != binary:
                raise ValueError(f"two binaries of {key}")
        else:
            key = assembled.launch_name(binary.kernel, binary.launch)
            if mosaic_found.setdefault(key, binary) != binary:
                raise ValueError(f"two binaries of {key}")
    found_reports = []
    for name in sorted(set(estimates) | set(mosaic_found)):
        text, binary = estimates.get(name, ""), mosaic_found.get(name)
        shared, tmem = SHARED.search(text), TENSOR_MEMORY.search(text)
        if shared and binary is not None and binary.shared is not None and not (
                int(shared.group(1)) <= binary.shared
                and (int(shared.group(1)) > 0 or binary.shared == 0)):
            raise ValueError(f"{name}'s estimate of {shared.group(1)} shared bytes pairs with a binary "
                             f"whose launch asks for {binary.shared}: the estimate is another kernel's")
        # A kernel no binary carries is no compiled kernel, whatever its PTX's compile says.
        unread = tuple(field for field, read in (
            ("shared bytes", shared is not None and binary is not None and binary.shared is not None),
            ("tensor memory columns", tmem), ("binary", binary),
            ("machine code", binary is None or binary.sass is not None)) if not read)
        kernel, launch, _ = assembled.kernel_of(name)
        found_reports.append(Report(
            kernel, binary.shared if binary is not None else None,
            sum(map(int, tmem.groups())) if tmem else None,
            None, None, unread, (modules or {}).get(name), launch,
            sass=tuple(binary.sass or ()) if binary is not None else (),
            launched=binary.launched if binary is not None else None,
            binary_registers=binary.registers if binary is not None else None,
            binary_spilled=binary.spills if binary is not None else None,
            binary_losses=(tuple(note.code for note in binary.notes if note.code in LOSSES)
                           if binary is not None else ()),
            threads=binary.threads if binary is not None else None,
            decreased=binary.decreased if binary is not None else None,
            raised=binary.raised if binary is not None else None,
            kind="mosaic_gpu"))
    for name in sorted(triton_found):
        binary = triton_found[name]
        tmem_known = binary.uses_tmem is False
        unread = tuple(field for field, read in (
            ("shared bytes", binary.shared is not None),
            ("tensor memory columns", tmem_known),
            ("machine code", binary.sass is not None)) if not read)
        found_reports.append(Report(
            binary.kernel, binary.shared, 0 if tmem_known else None,
            binary.registers, binary.spills, unread, None, binary.launch,
            sass=tuple(binary.sass or ()), launched=binary.launched,
            binary_registers=binary.registers, binary_spilled=binary.spills,
            threads=binary.threads, decreased=binary.decreased, raised=binary.raised,
            kind="triton", planned=False, index=binary.index))
    return found_reports


UNIQUIFIED = re.compile(r"__\d+$")
"""The suffix XLA gives a kernel name's later launches in a program (`recurrence_cumulated__1`)."""


@functools.cache
def staged_copy(shape: tuple[int, ...], dtype):
    """A Mosaic GPU kernel copying its operand through shared memory by TMA: the least Mosaic kernel a test
    compiles for a generation."""
    from jax.experimental.pallas import mosaic_gpu as plgpu

    def body(source, out, staged, barrier):
        plgpu.copy_gmem_to_smem(source, staged, barrier.at[0])
        plgpu.barrier_wait(barrier.at[0])
        plgpu.copy_smem_to_gmem(staged, out)
        plgpu.wait_smem_to_gmem(0)

    return plgpu.kernel(body, out_type=jax.ShapeDtypeStruct(shape, dtype), num_threads=1, thread_name="wg",
                        scratch_types=[plgpu.SMEM(shape, dtype), plgpu.Barrier(num_barriers=1)])


class Expected(NamedTuple):
    """What a public route's program shows compiled for a mesh of its GPUs (a case's `expected`): the mesh
    (`axes`, each axis's devices), each positional argument's placement on it (`specs`, a `PartitionSpec`
    each, None replicated), the launches it runs (`launches`, its kernel calls' names), an array a device's
    call of a launch reads (`shards`, by launch: some call of it reads an operand of this shape, a shard's
    where it runs per shard), and every collective it moves or sums by (`collectives`, each `(op, mesh
    axes)`: exactly these, `sharded.collective_axes` of its compiled program). A case missing any of them,
    or showing others, fails (`route_failures`)."""

    axes: tuple[tuple[str, int], ...]
    specs: tuple
    launches: frozenset[str]
    shards: Mapping[str, tuple[int, ...]] = MappingProxyType({})
    collectives: frozenset[tuple[str, frozenset[str]]] = frozenset()


def _device(generation: str, axes: tuple[tuple[str, int], ...] = (("data", 1),), memory: int | None = None
            ) -> Mesh:
    """A mesh of compile-only devices of `generation`, of `axes` (one device's by default), each stating
    `memory` where given (else the generation's least part's, `generation.target_config`)."""
    sizes = tuple(size for _, size in axes)
    devices = compile_only_gpus(generation, count=int(np.prod(sizes)), memory=memory)
    return Mesh(np.array(devices).reshape(sizes), tuple(name for name, _ in axes))


def lowered_for(fn, args, generation: str, expected: Expected | None = None, *, memory: int | None = None):
    """`fn` traced on `args`, its abstract leaves placed on compile-only devices of the CUDA `generation`
    (`_device`: one, replicated, or `expected`'s mesh, each argument by its spec, each device stating
    `memory` where given), and lowered as on that GPU (`assumed`, the mesh's abstract devices) within its
    block's shared memory: what XLA compiles for it, never run."""
    mesh = (_device(generation, memory=memory) if expected is None
            else _device(generation, expected.axes, memory=memory))
    specs = (None,) * len(args) if expected is None else expected.specs
    def placed_on(arg, sharding: NamedSharding):
        return jax.tree.map(lambda leaf: jax.ShapeDtypeStruct(leaf.shape, leaf.dtype, sharding=sharding)
                            if isinstance(leaf, jax.ShapeDtypeStruct) else leaf, arg)

    placed = tuple(placed_on(arg, NamedSharding(mesh, spec or PartitionSpec()))
                   for arg, spec in zip(args, specs, strict=True))
    # Deviceless Mosaic lowering defaults to Hopper's limit, not this target's.
    # Its bound checks the total allocation, including barriers outside the scratch estimate.
    # On one GPU, on the mesh's concrete device, as a run's start lowers on its compile-only GPU
    # (`jax.set_mesh`): certification then lowers each launch on the mesh the program's call does
    # (`report._certifying_placement`), and the program reads those lowerings back (the Pallas lowering
    # cache keys both), where an abstract mesh alone left certification a mesh of its own and the program
    # lowered every kernel again (a GEMM gate node's lowerings 33 missed and 1 hit, now 20 and 14; 118.9 s
    # to 111.0 s). Many devices' certification lowers on a mesh of its own whatever the program's.
    placing = jax.set_mesh(mesh) if mesh.size == 1 else jax.sharding.use_abstract_mesh(mesh.abstract_mesh)
    with (assumed(generation), placing,
          mgpu_core.artificial_shared_memory_limit(gpu_target(generation).shared_limit)):
        return jax.jit(fn).trace(*placed).lower()


def refused(record: dict) -> bool:
    """Whether a compiled record failed as a program: its error, or shared bytes past its block's limit
    (a Triton kernel's, or XLA's refusal of a block, which a Mosaic GPU program states only then)."""
    return "error" in record or ("shared" in record and record["shared"] > record["limit"])


def failures(found: list[dict]) -> list[str]:
    """Each compiled record's failure, if any: its error, or its shared bytes past its block's limit."""
    return [f"{record['name']}: {record['error']}" if "error" in record else
            f"{record['name']}: {record['shared']} shared bytes, limit {record['limit']}"
            for record in found if refused(record)]


def compile_kernels(cases, generation: str) -> list[dict]:
    """Each case (`name`, `call()` giving the kernel and abstract operands) on the CUDA `generation`,
    lowered as on that GPU on this host (`assumed`, `lowered_for`) and compiled by XLA for a compile-only
    device of it, never run: its name, the generation's block limit, the shared bytes its Triton kernels
    launch with (the most of any; those XLA refused, where it refused one), or the error, and the custom
    kernels its executable launches, a count of each by name (`launches`, `assembled.launched_kernels`).

    A cheap first filter: a kernel that does not compile or takes more shared memory than its GPU's
    block holds fails here as it would there, before a GPU is paid for. A program whose executable carries
    no Triton kernel fails too: nothing states its kernel's shared bytes (`triton_evidence`)."""
    found: list[dict] = []
    for case in cases:
        record: dict = {"name": case.name, "generation": generation,
                        "limit": gpu_target(generation).shared_limit}
        found.append(record)
        compiled = _compiled(case, generation, record)
        if compiled is None:
            continue
        launched, calls = compiled
        record.update(triton_evidence(calls, launched),
                      launches=Counter(UNIQUIFIED.sub("", name) for name, _ in launched))
    return found


def triton_evidence(calls: dict[str, int], launched: list[tuple[str, int]]) -> dict:
    """What a program's executable says of its Triton kernels (`launched`, `assembled.launched_kernels`: each
    custom kernel it launches by name, with the shared bytes its launch asks), its calls by name with the
    call sites of each (`calls`, the lowering reader's `triton_kernels`, which owns the inventory): the
    largest shared bytes a call launches with, or why it says nothing. Each Triton call launches a kernel of
    its own, named as the call is, XLA numbering a name's later calls (recurrence_cumulated__1); a call with
    no such launch, or a program that calls no Triton kernel, is no evidence its kernel compiled within its
    block (row 1381). The executable's, not XLA's dumped thunk sequence, which a GPU host's run omitted
    (IG-FINAL3: every Triton decode compile cell)."""
    launches: dict[str, list[int]] = {}
    for name, shared in launched:
        launches.setdefault(UNIQUIFIED.sub("", name), []).append(shared)
    if not calls:
        return {"error": "XLA's program calls no Triton kernel"}
    unlaunched = sorted(name for name, count in calls.items() if len(launches.get(name, ())) < count)
    if unlaunched:
        return {"error": f"no launch of its own states the shared bytes of {', '.join(unlaunched)}"}
    return {"shared": max(size for name in calls for size in launches[name])}


def _uncertified_since(uncertified: dict) -> list[str]:
    """Each launch the lowering could not certify since `uncertified` was read (`report.uncertified`)."""
    return [f"{type(key[0]).__name__ if not isinstance(key[0], str) else key[0]} at {key[1]}: {why}"
            for key, why in report.uncertified().items() if key not in uncertified]


def _certified_since(count: int) -> list[dict]:
    """Each launch certification compiled since the first `count` (`report.certifications`): its op and
    config and each kernel's registers, spilled bytes and verdict (`Binary.refused`), what a cell a family
    declines proves the decline by, read where a process of its own compiled it (`compiled_apart`)."""
    return [{"op": found.op, "config": repr(found.config),
             "kernels": {name: [binary.registers, binary.spills, binary.refused]
                         for name, (_, binary) in found.kernels.items()}}
            for found in report.certifications()[count:]]


def _compiled(case, generation: str, record: dict,
              directory: str | None = None) -> tuple[list[tuple[str, int]], dict[str, int]] | None:
    """`case` lowered as on the CUDA `generation` (`lowered_for`) and compiled by XLA for a
    compile-only device of it: the custom kernels its executable launches (`assembled.launched_kernels`) and
    the lowered program's Triton calls by name
    (`triton_kernels`), or None, `record` holding why: the error, or the shared bytes of a block XLA
    refused. `record['modules']` holds each Mosaic GPU kernel's module (its kernel hash) by its name and
    launch, and `record['certified']` each one certification compiled alone in the process
    (`report.certifications`). Given a `directory`, its Mosaic GPU kernels' evidence too (`_dumped`):
    `record['estimates']` each one's resource estimate Pallas prints as it lowers, `record['binaries']` each
    one's binary (`assembled.binaries`), and in `directory` the PTX Mosaic dumps as it compiles (`_dumped`), a
    `<kernel>.ptx` each."""
    fn, args = case.call()
    expected = getattr(case, "expected", None)
    # Each launch's derived config is certified as it traces, as a start on the GPU certifies it
    # (`report.certified`), on a compile-only device of the generation: its kernels compiled then, each
    # module once a process, so their PTX prints as the program lowers, not as it compiles. Here, in the
    # process of the generation's capability (`compile_mosaic_kernels`), never in a bare lowering.
    lowering, compiling = ((Path(directory, "lowering"), Path(directory, "compiling")) if directory
                           else (None, None))
    for dumped in (lowering, compiling):
        if dumped is not None:
            dumped.mkdir()
    estimating = _dumped(str(lowering)) if lowering is not None else contextlib.nullcontext()
    uncertified = report.uncertified()
    certifying = len(report.certifications())
    try:
        with estimating, report.certifying(compile_only_gpus(generation)[0]):
            lowered = lowered_for(fn, args, generation, expected)
    except Exception as error:  # A case that does not lower is its own failure.
        # One a block's shared memory does not hold asks its bytes, as XLA's refusal of a Triton kernel does.
        refused = MOSAIC_REFUSED.search(str(error))
        if refused is None:
            record["error"] = f"it does not lower: {str(error)[-800:]}"
        else:
            record["shared"] = int(refused.group(1))
        # A derivation the assembler exhausted refuses at trace: preserve typed exhaustion, uncertified
        # failures and certifications so unrelated lowering failures cannot masquerade as exhaustion (6730).
        record["exhausted"] = isinstance(error, report.Exhausted)
        record["uncertified"] = _uncertified_since(uncertified)
        record["certifications"] = _certified_since(certifying)
        if lowering is not None:
            # Every offer refused under the certifying build, each judged under the others too: one another
            # build holds is a launch production there runs that no gate compiled (row 10766).
            record["refused_builds"] = _judged_across_builds(
                certifying, printed_modules(dumps(str(lowering), ".ptx")), generation)
        return None
    # A launch the lowering could not certify (`report.certified`) is a failure of its own: its run would
    # find its spills only as its whole program compiles.
    record["uncertified"] = _uncertified_since(uncertified)
    calls = [call for call in kernel_calls(lowered, unrun=True) if call.kind == "mosaic_gpu"]
    # A tensor-core commit past another warp's wait wedges the launch where it runs: the case fails as one
    # that does not compile, in every gate reading its records (`failures`, row 12144).
    if unsynced := [found for call in calls for found in unsynced_commits(call.ir)]:
        record["error"] = "its tensor-core commits pass another warp's wait: " + "; ".join(unsynced)
        return None
    modules = report.kernel_modules(calls)
    record["modules"] = modules
    # Each kernel certification compiled alone in this process, by name and launch: its module.
    record["certified"] = {name: module for found in report.certifications()
                           for name, (module, _) in found.kernels.items()}
    # Each launch certification compiled for this case, its op and config and each kernel's registers, spilled
    # bytes and verdict (`Binary.refused`): what a cell a family declines proves the decline by, read where
    # a process of its own compiled it (`compiled_apart`) as here.
    record["certifications"] = _certified_since(certifying)
    if directory is not None:
        record["estimates"] = _estimates(calls, dumps(str(lowering), ".resources.txt"))
    # A process whose persistent compilation cache is on keeps it on here (JAX settles that once a
    # process): a compile-only device's entry reads back as unloadable, with a warning, and compiles.
    printing = _dumped(str(compiling)) if compiling is not None else contextlib.nullcontext()
    try:
        with printing:
            executable = lowered.compile()
    except jax.errors.JaxRuntimeError as error:
        asked = report.shared_asked(error)
        if asked is None:
            record["error"] = f"XLA does not compile it: {str(error)[-800:]}"
        else:
            record["shared"] = asked
        return None
    if directory is not None:
        record["binaries"] = [dataclasses.asdict(found)
                              for found in assembled.binaries(executable, decoded=True)]
        # The lowering's print read once: the settled kernels' modules and the refused configs' alike.
        lowered_modules = printed_modules(dumps(str(lowering), ".ptx"))
        written({**lowered_modules, **printed_modules(dumps(str(compiling), ".ptx"))}, directory, modules)
        # Each config certification refused, judged under every build its generation's GPUs run (row 10766).
        record["refused_builds"] = _judged_across_builds(certifying, lowered_modules, generation)
    if expected is not None:
        record["route"] = _route(lowered, executable, _device(generation, expected.axes))
    record["thunks"] = assembled.launched_thunks(executable)
    return assembled.launched_kernels(executable), triton_kernels(lowered)


def _estimates(calls: list, printed: str) -> dict[str, str]:
    """Each Mosaic GPU call's resource estimate by its kernel's name and launch (`assembled.launch_name`),
    from what its lowering printed: Mosaic prints one each time it builds a kernel's module, beside the hash
    that names its kernel (`<name> <hash> Resources(...)`), which a call's `config` holds (its first 16 hex
    digits). A module built once and reused (a lowering JAX cached, a launch certified as it traced,
    `report.certified`) prints one, its estimate kept by its module (`ESTIMATES`)."""
    for name, hashed, estimate in PRINTED_ESTIMATE.findall(printed):
        del name
        ESTIMATES[hashed[:16]] = estimate
    return {assembled.launch_name(call.name, call.launch): ESTIMATES[call.config] for call in calls
            if call.config in ESTIMATES}


PRINTED_ESTIMATE = re.compile(r"^(\S+) ([0-9a-f]{64}) (Resources\(.*\))$", re.M)
"""A Mosaic GPU kernel's resource estimate as it prints it (`core.py`'s dump: its module's name, its kernel's
hash and the estimate)."""


ESTIMATES: dict[str, str] = {}
"""Each Mosaic GPU kernel's resource estimate this process read, by its module (its kernel hash)."""


def write_modules(lowering: str, compiling: str, directory: str, kernels: Collection[str]) -> None:
    """Each PTX module of the program's `kernels` (by name and launch, `assembled.launch_name`) Mosaic printed
    (`PTX_MODULE`) into `directory` as `<kernel>.ptx`, its kernel's name and launch its entry's
    (`assembled.kernel_of`): one certification assembled as the program lowered (`report.certified`), which
    its compile reuses, or one its compile assembled. A module the compile assembled supersedes
    certification's of its name and launch, which the program does not run (a gradient's forward is another
    kernel than the one certified, the recurrence template's); one of no kernel of the program is a config
    certification refused. Two modules of one name and launch in one print raise."""
    written({**printed_modules(lowering), **printed_modules(compiling)}, directory, kernels)


def written(modules: Mapping[str, str], directory: str, kernels: Collection[str]) -> None:
    """Each module of `modules` (`printed_modules`) of the program's `kernels` into `directory` as
    `<kernel>.ptx` (`write_modules`)."""
    for name, part in modules.items():
        if name in kernels:
            Path(directory, f"{name}.ptx").write_text(part)


def printed_modules(printed: str) -> dict[str, str]:
    """Each PTX module Mosaic GPU printed in `printed` (`PTX_MODULE`), whole, by its kernel's name and launch
    (`assembled.launch_name`, its entry's: `assembled.kernel_of`). Two modules of one name and launch in one
    print raise."""
    modules: dict[str, str] = {}
    for part in printed.split(PTX_MODULE)[1:]:
        entry = PTX_ENTRY.search(part)
        if entry is None:
            raise ValueError(f"a printed PTX module names no entry: {part[:200]}")
        name = assembled.launch_name(*assembled.kernel_of(entry.group(1)))
        if name in modules:
            raise ValueError(f"two PTX modules of {name}")
        modules[name] = "//\n" + PTX_MODULE + part
    return modules


def refused_across_builds(certifications, printed: dict[str, str], builds: Sequence[str],
                          read: Callable[[str, str], Assembled]) -> list[dict]:
    """Each Mosaic GPU launch config certification refused (`report.Certification.refused`) judged under every
    build of `builds` a GPU of its generation runs (row 10766): `refused` where that build's assembler
    refuses a kernel of it too (`read`, its ptxas's report of a kernel's PTX under a build: a spill or a
    serialization, `assembled.refuses`), production there stepping past it as the gate did; else production
    on that build certifies it, a launch the gate's settled kernels are not, held here to the gate's own
    kernel checks under that build: `qualified` where no kernel of it notes a loss the gate fails
    (`LOSSES`), else `failed` and the codes. Each kernel's PTX is the module Mosaic GPU printed as it
    certified (`printed`, `printed_modules`, by name and launch; else by its module where an earlier case
    printed it, `PTX`): a config whose kernel printed none here (its module compiled before the gate) is
    `unverified`. A Triton launch's config is not judged here: no print of its PTX is read (its certifying
    build's verdict alone). Each `{op, config, builds}`."""
    judged = []
    for found in certifications:
        triton = any(binary.kind != "mosaic_gpu" for _, binary in found.kernels.values())
        if not found.refused or triton:
            continue
        sources = {}
        for name, (module, _) in found.kernels.items():
            if name in printed:
                PTX[module] = printed[name]
            sources[name] = PTX.get(module)
        verdicts = {}
        for build in builds:
            if None in sources.values():
                verdicts[build] = "unverified"
                continue
            reads = [read(ptx, build) for ptx in sources.values()]
            losses = sorted({code for each in reads for code in each.losses if code in LOSSES})
            if any(assembled.refuses(each.spilled, each.losses) for each in reads):
                verdicts[build] = "refused"
            else:
                verdicts[build] = f"failed: {', '.join(losses)}" if losses else "qualified"
        judged.append({"op": found.op, "config": repr(found.config), "builds": verdicts})
    return judged


def _judged_across_builds(certifying: int, printed: dict[str, str], generation: str) -> list[dict]:
    """`refused_across_builds` of the certifications since the first `certifying`, their PTX as the case's
    lowering printed it (`printed`, `printed_modules`)."""
    return refused_across_builds(report.certifications()[certifying:], printed, judged_builds(generation),
                                 functools.partial(_assembled_under, generation))


def refused_across_build_failures(record: dict) -> list[str]:
    """Each config `record`'s certification refused that a build of its generation's holds but fails the
    gate's kernel checks under, or that no build's assembler judged here (`refused_across_builds`): a launch
    production on that build may run that the gate does not qualify."""
    return [f"{record['name']}: {judged['op']} at {judged['config']} refused as it certified, "
            f"{verdict} under {build}"
            for judged in record.get("refused_builds", ()) for build, verdict in judged["builds"].items()
            if verdict not in ("refused", "qualified")]


def _route(lowered, executable, mesh: Mesh) -> dict:
    """What a compiled route shows (`Expected`): its launches by name, the operands each of their calls
    reads, and its collectives over `mesh`, JSON's types (a record a process of its own writes back). Its
    launches are those a run of it reaches (`kernel_calls`), not a loop's of no trips, which the resource
    compile reads all the same (`unrun`): a route whose launch never runs does not take it."""
    calls = kernel_calls(lowered)
    shards: dict[str, list] = {}
    for call in calls:
        shards.setdefault(call.name, []).append([list(shape) for shape in call.operands])
    return {"launches": sorted(shards), "shards": shards,
            "collectives": sorted([op, sorted(axes)]
                                  for op, axes in collective_axes(executable, mesh))}


def route_failures(cases, found: list[dict]) -> list[str]:
    """Each routed case (its `expected`) whose compiled program misses a launch it states, reads no shard it
    states in any call of a launch, or moves or sums by collectives other than the plan's, or that left no
    program to read: the route's own evidence, beside its kernels' resources."""
    failed = []
    for case, record in zip(cases, found, strict=True):
        if (expected := getattr(case, "expected", None)) is None:
            continue
        if (route := record.get("route")) is None:
            why = record.get("error", "none")
            failed.append(f"{case.name}: no compiled program states its route ({why})")
            continue
        if missing := sorted(expected.launches - set(route["launches"])):
            failed.append(f"{case.name}: no launch of {', '.join(missing)} (it ran {route['launches']})")
        for name, shape in expected.shards.items():
            calls = route["shards"].get(name, [])
            if not any(list(shape) in operands for operands in calls):
                failed.append(f"{case.name}: no call of {name} reads a {list(shape)} shard "
                              f"(its calls read {calls})")
        collectives = {(op, frozenset(axes)) for op, axes in route["collectives"]}
        if collectives != expected.collectives:
            failed.append(f"{case.name}: collectives {sorted(map(_named, collectives))}, where its plan "
                          f"states {sorted(map(_named, expected.collectives))}")
    return failed


def _named(collective: tuple[str, frozenset[str]]) -> str:
    """A collective as a failure names it: its op over its axes."""
    op, axes = collective
    return f"{op} over {'/'.join(sorted(axes)) or 'no axis'}"


def mosaic_kernels(record: dict) -> list[dict]:
    """Each Mosaic GPU kernel's report from `record`'s evidence (`reports`, `_compiled`), as a record a test's
    process of its own writes back as JSON (`compile_mosaic_kernels`)."""
    # A binary's notes come back from its record as their fields (`dataclasses.asdict`).
    binaries = [assembled.Binary(**{**found, "notes": tuple(assembled.AssemblerNote(**note)
                                                          for note in found.get("notes", ()))})
                for found in record.get("binaries", ())]
    return [dataclasses.asdict(found) for found in
            reports(record.get("estimates", {}), binaries, record.get("modules"))]


_DUMPING = threading.Lock()
"""Held while Mosaic's dumps are on (`_dumped`)."""


@contextlib.contextmanager
def _dumped(directory: str):
    """Mosaic GPU's PTX and resource estimates of each module the block builds or compiles written into
    `directory`, each module's own files (`<basename>.ptx`, `<basename>.resources.txt`): the dumps a module's
    options take (`get_or_set_dump_options`, MOSAIC_GPU_DUMP_TO with only these kinds named), read back by
    `dumps`, never a print. MOSAIC_GPU_DUMP_TO with no kind named turns every dump on, its layout inference's
    constraint system among them, each variable printing its operation: 47.6 of a Kimi Linear A100 forward
    cell's 138 seconds (cProfile, armada, 9e65ee222). The gate compiles one case at a time in its process,
    which sets nothing else, as Mosaic reads these settings in every compile."""
    switches = {"MOSAIC_GPU_DUMP_TO": directory, "MOSAIC_GPU_DUMP_PTX": "1", "MOSAIC_GPU_DUMP_RESOURCES": "1"}
    with _DUMPING:
        before = {name: os.environ.get(name) for name in switches}
        os.environ.update(switches)
        try:
            yield
        finally:
            for name, value in before.items():
                if value is None:
                    os.environ.pop(name, None)
                else:
                    os.environ[name] = value


def dumps(directory: str, suffix: str) -> str:
    """The text of every dump of `suffix` in `directory` (`_dumped`), in its files' order."""
    return "".join(path.read_text() for path in sorted(Path(directory).glob(f"*{suffix}")))


_BINARY_CAPABILITY: list[tuple[int, int]] = []
"""The compute capability this process's Mosaic GPU binary pass is registered with: the first kernel's it
compiled. jaxlib registers the pass once a process and assembles every later kernel for that capability
(custom_call.cc's GetPassPipeline; an sm_90a kernel after an sm80 one fails in ptxas, 'SM version
specified by .target is higher than default SM version assumed', and an sm80 kernel after an sm90 one is
assembled for sm90). Production compiles for one GPU a process; the gates compile for several."""


class Gated(str):
    """A generation a compile gate's cell compiles for (`gate_generations`): the typed fact a process of its
    own gathers the session's cells of one capability by (`compiled_apart`)."""



def stated_outputs(lowered: jax.stages.Lowered, target: str | None = None) -> list[tuple[int, list | None]]:
    """Each custom call of `lowered` (of the call target `target`, every one where None), in the order JAX
    lowered them, a call no run reaches among them (`_read`'s `unrun`: XLA compiles it all the same): the
    outputs it defines (its results less those aliasing an operand, a ref it writes in place) and the
    dimensions it states them by (`outputs.OUTPUT_DIMS`, parsed: a list an output, its every dimension's
    `[operand, axis]` pairs; None where it states none), as XLA's compiler reads its frontend attribute."""
    from jax.extend.mlir import ir

    from dew.nn.kernels import lowered as reading
    from dew.nn.kernels.templates.outputs import OUTPUT_DIMS

    def read(called: str, operation) -> tuple[int, list | None] | None:
        if target is not None and called != target:
            return None
        aliased = (len(ir.ArrayAttr(operation.attributes["output_operand_aliases"]))
                   if "output_operand_aliases" in operation.attributes else 0)
        stated = reading._frontend(operation.attributes).get(OUTPUT_DIMS)
        return len(operation.results) - aliased, None if stated is None else json.loads(stated)

    return [call for call, _ in reading._read_calls(lowered, read, unrun=True)]

def gate_generations(dtype=jnp.bfloat16, *, stated: bool = False, scoped: bool = False, tpu: bool = False,
                     needs: Callable[[Any, Any], bool] | None = None) -> tuple[Gated, ...]:
    """The generations a compile gate's cells take for a template's launches of `dtype` (its launch's
    `stated`, `scoped` and `tpu`, as it asks `bundles.of`): one for each CUDA architecture Dew names a device
    of whose bundles serve the launch (`bundles.of` not None), the earliest named, so its launches are
    compiled on every family they run on (each architecture's multiprocessor and issuers,
    `generation.architecture`), never on a typed list (a recurrence gate of sm80 and sm90 alone left seven
    sm100 launches unseen). `needs(family, architecture)` is the
    typed fact a cell that is one family's by nature needs of it (an issuer, an instruction); every family's
    where None."""
    from dew.nn.kernels import generation
    from dew.nn.kernels.templates import bundles

    found: list[tuple[Any, str]] = []
    for name in sorted((name for name in generation.TARGETS if capability(name) is not None), key=capability):
        architecture = generation.architecture(name)
        family = bundles.of(name, dtype, stated=stated, scoped=scoped, tpu=tpu)
        if family is None or any(architecture == seen for seen, _ in found):
            continue
        if needs is None or needs(family, architecture):
            found.append((architecture, name))
    return tuple(Gated(name) for _, name in found)


def compile_mosaic_kernels(cases, generation: str) -> list[dict]:
    """Each Mosaic GPU case (`name`, `call()` giving the kernel and abstract operands) compiled as
    `compile_kernels` compiles Triton's, for a compile-only device of the CUDA `generation`, with Mosaic's
    own reports dumped (`_dumped`): its name, the generation's shared-memory and tensor-memory limits
    (`GpuTarget.tmem_columns`, 0 where it has none), and each of its kernels' report (`mosaic_kernels`),
    or the error. In a process that compiled Mosaic kernels for another capability
    (`_BINARY_CAPABILITY`) these are the records its process of its own gives (`compiled_apart`), and so where
    a module of its kernels was compiled in this process before the gate's, outside it, so that no PTX of
    it was dumped (`_undumped`: an earlier test certified the same launch; Mosaic compiles a module once a
    process): the test's own process, which compiles it first (train 957's red, the B200 gathered cells'
    producer read as None)."""
    wanted = capability(generation)
    test = os.environ.get("PYTEST_CURRENT_TEST", "").rsplit(" ", 1)[0]
    call = _CALLS[test]
    _CALLS[test] += 1
    if _BINARY_CAPABILITY and _BINARY_CAPABILITY[0] != wanted and apart_records.RECORDS not in os.environ:
        return compiled_apart(wanted, test, call)
    _BINARY_CAPABILITY[:] = _BINARY_CAPABILITY or [wanted]
    found = _compiled_here(cases, generation)
    if apart_records.RECORDS in os.environ:
        apart_records.written(Path(os.environ[apart_records.RECORDS]), test, call, found)
    elif _undumped(found):
        return compiled_apart(wanted, test, call, alone=True)
    return found


def _undumped(found: list[dict]) -> bool:
    """Whether a kernel of `found`'s records has no PTX this process dumped (`_compiled_here`'s `dumped`)."""
    return any(not kernel["dumped"] for record in found for kernel in record.get("kernels", ()))


_CALLS: Counter[str] = Counter()
"""Each test's `compile_mosaic_kernels` calls so far, by node id: a process of its own keeps a test's records
by their order."""

_APART: dict[tuple[int, int] | str, Path] = {}
"""The directory each process of its own wrote, by the capability whose cells it ran, or by the one test it
ran where that test states no capability of the gate's (`compiled_apart`)."""


def compiled_apart(wanted: tuple[int, int], test: str, call: int, *, alone: bool = False) -> list[dict]:
    """The records of `test`'s `call`-th Mosaic GPU compile, for a capability other than the one this process
    compiles for, from a pytest process of its own: one a capability, the first test to ask it starting it
    with every test of the session whose cells state it (`_stated`), so a test of another capability costs
    no process of its own; a test it did not run (one that states no capability of the gate's) its own.
    Read only where the test passed there, as its records are written before its own checks and teardown
    (row 1877). With `alone`, the test's own process, which runs it and nothing before it."""
    if alone:
        if test not in _APART:
            _APART[test] = _ran_apart([test])
        return apart_records.read(_APART[test], test, call)
    if wanted not in _APART:
        _APART[wanted] = _ran_apart([test, *(item.nodeid for item in apart_records.SESSION
                                             if item.nodeid != test and _stated(item) == wanted)])
    directory = _APART[wanted]
    if not apart_records.ran(directory, test):
        if test not in _APART:
            _APART[test] = _ran_apart([test])
        directory = _APART[test]
    return apart_records.read(directory, test, call)


def _stated(item) -> tuple[int, int] | None:
    """The capability a session's test compiles for, where its cell states one generation of the gate's
    (`Gated`); None for any other test."""
    stated = {capability(value) for value in getattr(getattr(item, "callspec", None), "params", {}).values()
              if isinstance(value, Gated)}
    return stated.pop() if len(stated) == 1 else None


def _ran_apart(tests: list[str]) -> Path:
    """The directory a pytest process of its own wrote running `tests`: their records, their outcomes and its
    output (`apart_records`), kept until this process exits."""
    directory = Path(tempfile.mkdtemp(prefix="dew-mosaic-apart-"))
    atexit.register(shutil.rmtree, directory, ignore_errors=True)
    ran = subprocess.run([sys.executable, "-m", "pytest", *tests, "-q", "-p", "no:cacheprovider"],
                         cwd=Path(__file__).parent.parent,
                         env={**os.environ, apart_records.RECORDS: str(directory)},
                         capture_output=True, text=True, check=False)
    (directory / "output.txt").write_text(ran.stdout + ran.stderr)
    return directory


COMPILED: dict[str, dict] = {}
"""Each Mosaic GPU kernel's registers and spills as the GPU compiles its PTX (`_compiled_reports`), by its
module: Mosaic compiles a module once a process, so a later case of the same module prints no PTX
(`inherited`)."""


def inherited(kernel: dict, compiled: dict[str, dict], generation: str) -> dict:
    """`kernel`'s record (`mosaic_kernels`) with its registers and spills, their only source: as the GPU
    compiles its PTX, this compile's (`compiled`, by its name and launch, `assembled.launch_name`), which this
    process keeps by its module (`COMPILED`), or, where Mosaic compiled the same module before in this process
    and so printed no PTX, that compile's. A kernel neither covers takes its executable's binary's where this
    process's builds are every build `generation`'s GPUs run (`_assembles_for`), its verdict then theirs;
    elsewhere it keeps them unread, another compiler's verdict no evidence of the GPU's."""
    if not kernel["planned"] and kernel["registers"] is not None and kernel["spilled"] is not None:
        return {**kernel, "ptxas": "its executable's binary"}
    name = assembled.launch_name(kernel["kernel"], kernel["launch"])
    if name in compiled:
        if kernel["module"] is not None:
            COMPILED[kernel["module"]] = compiled[name]
        return {**kernel, **compiled[name]}
    if kernel["module"] in COMPILED:
        return {**kernel, **COMPILED[kernel["module"]], "ptxas": "an earlier compile of its module"}
    if kernel["binary_registers"] is not None and _assembles_for(generation):
        # No PTX of it in this process (its module compiled before the gate's): its executable's binary
        # (`assembled.binaries`), as certification reads it, where this process's builds are every build the
        # generation's GPUs run (`_assembles_for`; train 956 F1, train 960 F1).
        return {**kernel, "registers": kernel["binary_registers"], "spilled": kernel["binary_spilled"],
                "ptxas": "its executable's binary"}
    unread = [*kernel["unread"], *(field for field in ("registers", "spills")
                                   if field not in kernel["unread"])]
    return {**kernel, "registers": None, "spilled": None, "unread": unread}


def _assembles_for(generation: str) -> bool:
    """Whether this process's Mosaic GPU binaries are the verdict of every build `generation`'s GPUs run: its
    CUDA builds installed (`dew._devices.cuda_builds`) theirs exactly (`dew._builds.generation_builds`), the
    gate judging a kernel by its worst result under each (an H100 runs cuda13 and cuda12, whose spills differ,
    rows 5671, 5759, 5761; a B200 cuda13 alone)."""
    return tuple(cuda_builds()) == generation_builds(generation)


PTX: dict[str, str] = {}
"""Each Mosaic GPU module's PTX this process printed, by its module, as `COMPILED` keeps its compile: a later
compile of the same module prints none, and its raise and its producer's decrease are read from this."""


BUILD_NVCC = {"cuda12": ("nvidia.cuda_nvcc", "12.9"), "cuda13": ("nvidia.cu13", "13.0")}
"""Each of JAX's CUDA builds (`dew._builds.CUDA_BUILDS`): the package of the nvcc wheel this environment
installs (locks/cpu.txt) and the release of the build's PTX compiler, which it must report: the CUDA release
the build's plugin was built against (Dew's JAX fork's .bazelrc, HERMETIC_CUDA_VERSION 13.0.0 and 12.9.1),
whose PTX compiler, linked into the plugin (Mosaic GPU's `GetAssemblyToBinaryCompilationProvider`:
libnvptxcompiler), compiles a Mosaic GPU kernel's PTX on a GPU running that build, whatever nvcc is installed
beside it: a B200 compiled with 13.0 where 13.4 held kernels 13.0 spilled (rows 5671, 5759)."""


@functools.cache
def ptxas_of(build: str) -> Path:
    """The ptxas that judges kernels as a GPU running JAX's CUDA `build` compiles them: its nvcc wheel's
    (`BUILD_NVCC`), refused unless its release is the build's PTX compiler's (`BUILD_NVCC`), naming the
    ptxas, its version and the build, so a relock that moves the wheel fails the gate rather than judging
    with another compiler."""
    package, release = BUILD_NVCC[build]
    found = importlib.util.find_spec(package)
    if found is None:
        raise RuntimeError(f"no {package} in this environment: the gate judges {build}'s GPUs' kernels with "
                           f"its ptxas, CUDA {release}'s")
    ptxas = Path(next(iter(found.submodule_search_locations or ()))) / "bin" / "ptxas"
    if not ptxas.is_file():
        # A namespace another of its wheels installs (a CUDA library's) holds no assembler.
        raise RuntimeError(f"no ptxas in {package} here ({ptxas}): the gate judges {build}'s GPUs' kernels "
                           f"with CUDA {release}'s")
    reported = subprocess.run([str(ptxas), "--version"], capture_output=True, text=True, check=False).stdout
    if f"release {release}," not in reported:
        version = reported.strip().splitlines()[-1] if reported.strip() else "no version"
        raise RuntimeError(f"{ptxas} ({version}) would judge the kernels of every GPU running {build}, which "
                           f"compiles them with CUDA {release}'s PTX compiler")
    return ptxas


def assemblers(generation: str) -> tuple[Path, ...]:
    """The ptxas of each CUDA build this environment judges a GPU of `generation` under (`judged_builds`,
    newest first), the gate judging its kernels under every one (`_compiled_reports`): a B200 runs the cuda13
    build alone, whose PTX compiler held kernels 12.9 spilled 4 to 16 bytes of and spilled kernels 12.9 held
    (rows 5671, 5759 and 5761)."""
    return tuple(ptxas_of(build) for build in judged_builds(generation))


@functools.cache
def judged_builds(generation: str) -> tuple[str, ...]:
    """The CUDA builds this environment judges a GPU of `generation` under: on a host with no GPU (the
    kernel-compile environment, holding each build's nvcc beside the cuda12 plugin it compiles with:
    locks/cpu.txt), or an environment with no CUDA plugin, every build the generation runs
    (`generation_builds`); on a host with one, the builds of the CUDA plugin its environment installs among
    them, as a GPU node's environment holds its own build's toolchain alone (its cuda12 lock has no CUDA 13
    ptxas, which would become its CUDA root: rows 4162, 8769). A generation none of whose builds this GPU
    environment's plugin is is refused, never judged under none. Asked once a generation, as nvidia-smi
    answers in seconds."""
    builds = generation_builds(generation)
    if not cuda_builds() or nvidia_gpus() is None:
        return builds
    own = tuple(build for build in builds if build in cuda_builds())
    if not own:
        raise RuntimeError(f"{generation}'s GPUs run JAX's {', '.join(builds)} build, which this GPU host's "
                           f"environment ({', '.join(cuda_builds()) or 'no CUDA plugin'}) does not install: "
                           "its kernels are judged in the kernel-compile environment")
    return own

PROGRAMS = re.compile(r"\.minnctapersm (\d+)")
"""The programs a multiprocessor holds of a kernel at once (`.minnctapersm`, Mosaic's `min_blocks_per_sm`), as
ptxas bounds its registers by them (`cap`)."""


RELOCATABLE = not resources.RAISES_HONORED
"""Whether the GPU compiles a Mosaic GPU kernel's PTX relocatably, as jaxlib's Mosaic GPU does through
nvJitLink, where ptxas ignores a warpgroup's register raise (`resources.RAISES_HONORED`). The gate compiles
the PTX as the GPU does: a container without nvJitLink compiles Mosaic's whole-program, honoring raises the
GPU ignores."""


def _ptxas_text(ptx: str, generation: str, relocatable: bool, ptxas: Path | None = None) -> tuple[str, bool]:
    """ptxas's own report (`-v`) on the kernel `ptx` for the CUDA `generation`, compiled relocatably or
    whole-program (`relocatable`, `RELOCATABLE`) by `ptxas` (`assemblers`' first by default), and whether it
    took the kernel."""
    major, minor = capability(generation) or (0, 0)
    arch = f"sm_{major}{minor}{'a' if major >= 9 else ''}"
    with tempfile.NamedTemporaryFile("w", suffix=".ptx") as source:
        source.write(ptx)
        source.flush()
        relocating = ("--compile-only",) if relocatable else ()
        ran = subprocess.run([str(ptxas or assemblers(generation)[0]), f"-arch={arch}", "-v", *relocating,
                              source.name, "-o", os.devnull], capture_output=True, text=True, check=False)
    return ran.stdout + ran.stderr, ran.returncode == 0


def ptxas_notes(ptx: str, generation: str) -> str:
    """What ptxas says of the kernel `ptx` as the GPU compiles it (`RELOCATABLE`): its registers and spills,
    and the notes it makes of the code, a warpgroup MMA's serialization among them ("wgmma.mma_async
    instructions are serialized"), which the gate's registers and spills do not state."""
    return _ptxas_text(ptx, generation, RELOCATABLE)[0]


def _assembled_under(generation: str, ptx: str, build: str) -> Assembled:
    """ptxas's report of the kernel `ptx` for the CUDA `generation` under JAX's CUDA `build` (`ptxas_of`),
    compiled as the GPU compiles it (`RELOCATABLE`); a kernel it does not compile raises."""
    ptxas = ptxas_of(build)
    text, took = _ptxas_text(ptx, generation, RELOCATABLE, ptxas)
    if not took:
        raise RuntimeError(f"{ptxas} does not compile a kernel for {generation}: {text[-400:]}")
    return ptxas_read(text)


def _compiled_reports(directory: str, generation: str) -> dict[str, dict]:
    """Each kernel's registers a thread and spilled bytes as the GPU compiles the PTX Mosaic printed into
    `directory` (`_ptxas_text`, at its own entry), by its name and launch (`assembled.launch_name`), the most
    of each under every CUDA build the gate judges the generation under (`judged_builds`,
    `_assembled_under`) and every build's notes: its binary is its compile in this process, which may not be
    the GPU's (`RELOCATABLE`)."""
    found = {}
    for path in Path(directory).glob("*.ptx"):
        ptx = path.read_text()
        reads = [_assembled_under(generation, ptx, build) for build in judged_builds(generation)]
        worst = max(reads, key=lambda read: (read.spilled, read.registers))
        found[path.stem] = {"registers": worst.registers, "spilled": worst.spilled,
                            "losses": tuple(dict.fromkeys(code for read in reads for code in read.losses)),
                            "ptxas": "the GPU's compile of its PTX"}
    return found


def _compiled_here(cases, generation: str) -> list[dict]:
    """`compile_mosaic_kernels`' records, compiled in this process."""
    found: list[dict] = []
    for case in cases:
        # The program's own record (its error, or XLA's refusal of its block), its Mosaic kernels' reports the
        # evidence of their resources: a Triton launch line is none of theirs.
        models = dict(case.models or {})
        record: dict = {"name": case.name, "generation": generation,
                        "limit": gpu_target(generation).shared_limit,
                        "models": {name: model.record() for name, model in models.items()}}
        # Every compile of the case a real one (`dew._cache.uncached`): Mosaic prints a module's PTX, the
        # gate's evidence, only as it compiles it, and a program JAX's persistent cache loads compiles
        # nothing, its kernels' records then empty (train 953: three programs loaded from the shared cache
        # gave a B200's gathered cells no registers, no spills and no producer).
        # Its certifications' verdicts kept apart from the store a run reads (`tuning.verdicts_kept_in`), so
        # each config certifies here and prints its PTX, refused ones among them (row 10766).
        with (tempfile.TemporaryDirectory(prefix="dew-mosaic-") as directory, _cache.uncached(),
              tempfile.TemporaryDirectory(prefix="dew-verdicts-") as verdicts,
              tuning.verdicts_kept_in(verdicts)):
            _compiled(case, generation, record, directory)
            kernels = mosaic_kernels(record)
            # Each kernel's model its launch stated as it traced (`report.Launch.kernels`), whose producer
            # its schedule lowers to (`producer_failures`).
            record["stated_models"] = {
                assembled.launch_name(kernel["kernel"], kernel["launch"]): stated.record()
                for kernel in kernels if kernel["planned"] and kernel["launched"] is not None
                and (launch := report.traced(kernel["launched"])) is not None
                and (stated := launch.kernels.get(kernel["kernel"])) is not None}
            compiled = _compiled_reports(directory, generation)
            record["kernels"] = [inherited(kernel, compiled, generation) for kernel in kernels]
            printed = {path.stem: path.read_text() for path in Path(directory).glob("*.ptx")}
            for kernel in record["kernels"]:
                if not kernel["planned"]:
                    # Its cubin its evidence, read as it was made: no PTX of it to dump.
                    kernel["dumped"] = True
                    programs = 1
                else:
                    name = assembled.launch_name(kernel["kernel"], kernel["launch"])
                    if kernel["module"] is not None and name in printed:
                        PTX[kernel["module"]] = printed[name]
                    ptx = printed.get(name, PTX.get(kernel["module"], ""))
                    # Whether this process dumped its PTX: none where its Mosaic module compiled before the
                    # gate's.
                    kernel["dumped"] = bool(ptx)
                    programs = int(held.group(1)) if (held := PROGRAMS.search(ptx)) else 1
                with assumed(gpu_target(generation)):
                    kernel["cap"] = (kernel["raised"] if kernel["raised"] is not None
                                     else None if kernel["threads"] is None
                                     else resources.thread_share(kernel["threads"], programs))
        record["tmem_limit"] = gpu_target(generation).tmem_columns or 0
        found.append(record)
    return found


def mosaic_failures(found: list[dict], *, traced_models: bool = False) -> list[str]:
    """Compile errors, spills, missing or excessive shared/TMEM allocations, a launch its lowering did not
    certify (`report.certified`), and a producer its schedule lowers to other registers than its model
    states (`setmaxnreg.dec` against `RegisterModel.producer`: a launch's plan and its emission one fact).
    Whether a launch's registers hold is its certification's alone: the gate judges no register model. A
    kernel's planned shared bytes are its case's model's, or with `traced_models`, where its case states
    none, its launch's as it traced (a case settled as a call takes its tile, `KernelOp.lowering` at None)."""
    failed = failures(found)
    for record in found:
        # A config the certifying build refused that another holds, a case's every offer refused among them.
        failed += refused_across_build_failures(record)
        if refused(record):
            continue
        failed += [f"{record['name']}: a launch not certified, {why}"
                   for why in record.get("uncertified", ())]
        if not record["kernels"]:
            failed.append(f"{record['name']}: no Mosaic GPU kernel compiled")
        for kernel in record.get("kernels", ()):
            found_kernel = _report(kernel)
            if (why := found_kernel.failure(record["limit"], record["tmem_limit"])) is not None:
                failed.append(f"{record['name']} {found_kernel.kernel}: {why}")
            cased = record.get("models", {}).get(found_kernel.kernel)
            stated = (None if not found_kernel.planned
                      else cased if cased is not None or not traced_models
                      else record.get("stated_models", {}).get(found_kernel.traced))
            unplanned = stated is None or stated["shared"] is None
            if traced_models and found_kernel.planned and unplanned:
                # A settled case plans its shared bytes by its launch's traced model alone: none, or one
                # stating no shared bytes, is no evidence its allocation is the plan's.
                failed.append(f"{record['name']}: {found_kernel.kernel} states no traced model's shared "
                              f"bytes, its allocation unchecked against its plan")
            if stated is not None and stated["shared"] not in (None, found_kernel.shared):
                failed.append(f"{record['name']} {found_kernel.kernel}: its planner sized {stated['shared']} "
                              f"bytes of shared memory, the kernel asks for {found_kernel.shared}")
    return failed + producer_failures(found)


def producer_failures(found: list[dict]) -> list[str]:
    """Each kernel whose schedule lowers its producer to other registers than its model states, or none where
    its model states a producer whose program moves registers, or lowers it where its program moves none
    (`setmaxnreg.dec`, the record's `decreased`, against `RegisterModel.producer` and `moves`): a launch's
    plan and its emission one fact."""
    failed = []
    for record in found:
        for kernel in record.get("kernels", ()):
            found_kernel = _report(kernel)
            if not found_kernel.planned:
                continue
            stated = record.get("stated_models", {}).get(found_kernel.traced,
                                                          record.get("models", {}).get(found_kernel.kernel))
            if stated is None or not stated["producer"]:
                continue
            lowered = stated["producer"] if stated.get("moves", True) else None
            if kernel.get("decreased") != lowered:
                failed.append(f"{record['name']} {found_kernel.kernel}: its schedule lowers its producer to "
                              f"{kernel.get('decreased')} registers, its model {lowered}")
    return failed


def compiled_kernels(record: dict) -> set[str]:
    """The names of the kernels `record` compiled, as its models name them (`Report.kernel`)."""
    return {_report(kernel).kernel for kernel in record.get("kernels", ())}


def _report(kernel: dict) -> Report:
    stated = {field.name: kernel[field.name] for field in dataclasses.fields(Report)
              if field.name in kernel}
    return Report(**{**stated, "unread": tuple(kernel["unread"])})


TPU_TOPOLOGIES = {name: target.compile_topology for name, target in TARGETS.items()
                  if target.compile_topology is not None}
"""The compile-only topology of each TPU generation the gate compiles for (`GpuTarget.compile_topology`):
libtpu describes a host's chips, of which a case takes one device."""


@functools.cache
def _tpu_device(generation: str) -> Mesh:
    """A one-device mesh of a compile-only TPU of `generation`."""
    topology = topologies.get_topology_desc(TPU_TOPOLOGIES[generation], "tpu")
    return Mesh(np.array(topology.devices[:1]), ("data",))


def compile_tpu_kernels(cases, generation: str) -> list[dict]:
    """Each case compiled by libtpu for a compile-only TPU of `generation`, traced under its abstract mesh
    so a kernel's `get_tpu_info` reads that TPU: its name and generation, or the error, Mosaic's refusal
    of a kernel past its stated VMEM limit included."""
    mesh = _tpu_device(generation)
    replicated = NamedSharding(mesh, PartitionSpec())
    # The generation assumed as well as its mesh, so a kernel's facts are its target's
    # (`dew.nn.kernels.splash.block_sizes`' scoped VMEM).
    found: list[dict] = []
    for case in cases:
        record: dict = {"name": case.name, "generation": generation}
        found.append(record)
        fn, args = case.call()
        placed = jax.tree.map(lambda leaf: jax.ShapeDtypeStruct(leaf.shape, leaf.dtype, sharding=replicated)
                              if isinstance(leaf, jax.ShapeDtypeStruct) else leaf, args)
        try:
            with assumed(generation), jax.sharding.use_abstract_mesh(mesh.abstract_mesh):
                lowered = jax.jit(fn).trace(*placed).lower()
            lowered.compile()
        except Exception as error:  # A case that does not lower or compile is its own failure.
            # Mosaic TPU's refusal leads with its reason and ends with diagnostics: both ends kept.
            text = str(error)
            text = text if len(text) <= 1600 else f"{text[:800]} ... {text[-800:]}"
            record["error"] = f"{type(error).__name__}: {text}"
    return found


class Uncounted(grouped_matmul.MosaicGmm):
    """The grouped forward with a register model that counts nothing, so its derivation takes a tile its
    registers do not hold: a launch whose model misses. Its first tile is a paired product's widest, 128 x
    256, two accumulators of 128 registers a thread, which spills in every compile whatever its walk's
    addresses take (the paired 128 x 128 tile this launch took first spilled 16 bytes in the process's own
    compile only while its walk held a stage's addresses in registers, and none since the walk forms them
    where it uses them: `rings.opaque`); a narrower tile comes once a compile has refused a tile of its
    launch (`report.refused_launches`, the relowering's proposals included)."""

    def registers(self, ba, config, target=None):
        del target
        return 0

    def candidate(self, ba, config, target):
        return super().candidate(ba, config, target) and (
            config.block_n == 256 or bool(report.refused_launches()))
