"""SLOP034 (tools/lint_precisions.py): no contraction in the package names its precision outright outside
its precision policy."""

from tool_support import linted

SOURCE = ("import jax\n"
          "from jax import lax\n"
          "from jax.lax import Precision as P\n"
          "class Precision:\n"
          "    HIGHEST = 1\n"
          "def product(x, y):\n"
          "    \"\"\"At Precision.HIGHEST, as the reference.\"\"\"\n"
          "    # precision='highest' here would be outright\n"
          "    a = jax.numpy.dot(x, y, precision=jax.lax.Precision.HIGHEST)\n"
          "    b = jax.numpy.dot(x, y, precision=lax.Precision.HIGHEST)\n"
          "    c = jax.numpy.dot(x, y, precision=P.HIGHEST)\n"
          "    d = jax.numpy.dot(x, y, precision='highest')\n"
          "    return a + b + c + d + Precision.HIGHEST\n")
"""A module naming JAX's precision outright four ways (its lines 9 to 12), and where no product reads it:
a docstring, a comment and a local class of that name."""


def test_a_precision_named_outright_outside_the_policy_is_reported(tmp_path):
    """JAX's `Precision.HIGHEST`, through any name its enum is imported as, and 'highest' as a call's
    `precision=`, each reported in the package's source; a docstring, a comment and a local class of
    that name not."""
    assert linted(tmp_path, {"src/sparx/layer.py": SOURCE}) == [
        ("src/sparx/layer.py", line, "SLOP034") for line in (9, 10, 11, 12)]


def test_the_policy_and_a_generated_module_name_their_precisions(tmp_path):
    """The precision policy and the arithmetic catalog beneath it name precisions (`POLICY`), and so does a
    module its generator printed, its docstring opening as the generator's does (`GENERATED`): none
    reported. A module that names the generator anywhere but its docstring's opening is."""
    printed = '"""Generated by `python -m sparx.generate`; do not edit."""\n' + SOURCE
    mentioned = '"""A module, not one Generated by its generator."""\n' + SOURCE
    found = linted(tmp_path, {"src/sparx/nn/precision.py": SOURCE, "src/sparx/nn/programs.py": SOURCE,
                              "src/sparx/printed.py": printed, "src/sparx/mentioned.py": mentioned})
    assert found == [("src/sparx/mentioned.py", line, "SLOP034") for line in (10, 11, 12, 13)]
